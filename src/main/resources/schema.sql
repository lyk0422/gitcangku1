-- 设备工时保养判定：H2（MODE=MySQL）自动建表脚本。
-- 所有时刻字段均为 UTC（TIMESTAMP WITH TIME ZONE），分钟数为非负整数。

-- 设备主表：每台设备一行，版本号用于写操作乐观并发控制。
CREATE TABLE IF NOT EXISTS equipment (
    equipment_id VARCHAR(64) NOT NULL PRIMARY KEY,
    maintenance_period_minutes BIGINT NOT NULL,
    version BIGINT NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);
COMMENT ON TABLE equipment IS '设备主表：每台设备一行';
COMMENT ON COLUMN equipment.equipment_id IS '设备唯一标识（客户端提供）';
COMMENT ON COLUMN equipment.maintenance_period_minutes IS '保养周期（分钟），正整数，登记后不可修改';
COMMENT ON COLUMN equipment.version IS '设备版本号，初始 1；新增读数/修订/完成保养均校验 expectedVersion 并加一';
COMMENT ON COLUMN equipment.created_at IS '登记时刻（UTC）';

-- 工时读数当前值表：reading_id 设备内唯一，同设备同一采样时刻仅一条。
CREATE TABLE IF NOT EXISTS reading (
    equipment_id VARCHAR(64) NOT NULL,
    reading_id VARCHAR(64) NOT NULL,
    sampled_at TIMESTAMP WITH TIME ZONE NOT NULL,
    cumulative_minutes BIGINT NOT NULL,
    revision_no INT NOT NULL,
    certified BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    PRIMARY KEY (equipment_id, reading_id),
    CONSTRAINT uq_reading_sampled_at UNIQUE (equipment_id, sampled_at)
);
COMMENT ON TABLE reading IS '工时读数当前值：按采样时刻排序后累计分钟须单调不减';
COMMENT ON COLUMN reading.equipment_id IS '所属设备标识';
COMMENT ON COLUMN reading.reading_id IS '读数标识，设备内唯一';
COMMENT ON COLUMN reading.sampled_at IS 'UTC 采样时刻；同设备同一时刻仅允许一条读数';
COMMENT ON COLUMN reading.cumulative_minutes IS '当前累计工时（分钟），非负整数，随修订更新';
COMMENT ON COLUMN reading.revision_no IS '当前修订号，初始 1，每次修订加一';
COMMENT ON COLUMN reading.certified IS '是否为设备当前已认证读数：同设备同时仅一条为 TRUE；建保养工单时基线须为已认证读数';
COMMENT ON COLUMN reading.created_at IS '读数登记时刻（UTC）';
COMMENT ON COLUMN reading.updated_at IS '最近一次修订时刻（UTC）';
CREATE INDEX IF NOT EXISTS idx_reading_certified ON reading (equipment_id, certified);

-- 读数修订历史：每次修订追加一行，保留全部历史值。
CREATE TABLE IF NOT EXISTS reading_revision (
    equipment_id VARCHAR(64) NOT NULL,
    reading_id VARCHAR(64) NOT NULL,
    revision_no INT NOT NULL,
    cumulative_minutes BIGINT NOT NULL,
    request_id VARCHAR(128) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    PRIMARY KEY (equipment_id, reading_id, revision_no)
);
COMMENT ON TABLE reading_revision IS '读数修订历史：revision_no=1 为初始登记值，其后每行对应一次修订';
COMMENT ON COLUMN reading_revision.equipment_id IS '所属设备标识';
COMMENT ON COLUMN reading_revision.reading_id IS '读数标识';
COMMENT ON COLUMN reading_revision.revision_no IS '修订号，从 1 开始递增';
COMMENT ON COLUMN reading_revision.cumulative_minutes IS '该修订版本的累计工时（分钟）';
COMMENT ON COLUMN reading_revision.request_id IS '产生该修订的请求 requestId';
COMMENT ON COLUMN reading_revision.created_at IS '该修订生效时刻（UTC）';

-- 保养记录：锚定某读数的特定修订号，保存锚点时刻与工时快照，不允许删除。
CREATE TABLE IF NOT EXISTS maintenance (
    maintenance_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    equipment_id VARCHAR(64) NOT NULL,
    reading_id VARCHAR(64) NOT NULL,
    anchor_revision_no INT NOT NULL,
    anchor_sampled_at TIMESTAMP WITH TIME ZONE NOT NULL,
    anchor_cumulative_minutes BIGINT NOT NULL,
    request_id VARCHAR(128) NOT NULL,
    completed_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_maintenance_equipment ON maintenance (equipment_id, anchor_sampled_at);
COMMENT ON TABLE maintenance IS '保养记录：锚点时间须严格晚于上次保养锚点；作为锚点的读数不可再修订';
COMMENT ON COLUMN maintenance.maintenance_id IS '保养记录自增主键';
COMMENT ON COLUMN maintenance.equipment_id IS '所属设备标识';
COMMENT ON COLUMN maintenance.reading_id IS '锚点读数标识';
COMMENT ON COLUMN maintenance.anchor_revision_no IS '锚点读数在保养完成时的修订号';
COMMENT ON COLUMN maintenance.anchor_sampled_at IS '锚点读数的 UTC 采样时刻（快照）';
COMMENT ON COLUMN maintenance.anchor_cumulative_minutes IS '锚点读数在保养完成时的累计工时快照（分钟）';
COMMENT ON COLUMN maintenance.request_id IS '完成保养请求的 requestId';
COMMENT ON COLUMN maintenance.completed_at IS '保养完成登记时刻（UTC）';

-- 幂等去重表：requestId 全局唯一；仅成功结果占键，失败回滚不占键。
CREATE TABLE IF NOT EXISTS idempotency_request (
    request_id VARCHAR(128) NOT NULL PRIMARY KEY,
    operation VARCHAR(48) NOT NULL,
    request_fingerprint VARCHAR(512) NOT NULL,
    response_body CLOB NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);
COMMENT ON TABLE idempotency_request IS '写操作幂等去重：同键同参重放原成功结果，同键异参返回 409';
COMMENT ON COLUMN idempotency_request.request_id IS '全局唯一请求标识';
COMMENT ON COLUMN idempotency_request.operation IS '操作类型（登记设备/新增读数/修订/完成保养）';
COMMENT ON COLUMN idempotency_request.request_fingerprint IS '业务参数指纹（不含 requestId），用于同键异参判定';
COMMENT ON COLUMN idempotency_request.response_body IS '原成功响应报文（JSON），重放时原样返回';
COMMENT ON COLUMN idempotency_request.created_at IS '首次成功处理时刻（UTC）';

-- 保养工单：建单时冻结基线读数快照与左闭右开登记窗口；状态机串行推进。
CREATE TABLE IF NOT EXISTS work_order (
    work_order_id VARCHAR(64) NOT NULL,
    equipment_id VARCHAR(64) NOT NULL,
    version BIGINT NOT NULL,
    status VARCHAR(16) NOT NULL,
    baseline_reading_id VARCHAR(64) NOT NULL,
    baseline_revision_no INT NOT NULL,
    baseline_sampled_at TIMESTAMP WITH TIME ZONE NOT NULL,
    baseline_cumulative_minutes BIGINT NOT NULL,
    window_start TIMESTAMP WITH TIME ZONE NOT NULL,
    window_end TIMESTAMP WITH TIME ZONE NOT NULL,
    last_valid_reading_id VARCHAR(64),
    last_valid_sampled_at TIMESTAMP WITH TIME ZONE,
    last_valid_cumulative_minutes BIGINT,
    last_valid_revision_no INT,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    started_at TIMESTAMP WITH TIME ZONE,
    closed_at TIMESTAMP WITH TIME ZONE,
    cancelled_at TIMESTAMP WITH TIME ZONE,
    terminated_at TIMESTAMP WITH TIME ZONE,
    terminate_reason VARCHAR(512),
    PRIMARY KEY (equipment_id, work_order_id)
);
COMMENT ON TABLE work_order IS '保养工单：冻结基线读数与登记窗口；CREATED→IN_PROGRESS→CLOSED，CREATED→CANCELLED，IN_PROGRESS→TERMINATED';
COMMENT ON COLUMN work_order.work_order_id IS '工单标识（客户端提供），设备内唯一';
COMMENT ON COLUMN work_order.equipment_id IS '所属设备标识';
COMMENT ON COLUMN work_order.version IS '工单版本号，初始 1，开始/关闭/取消/终止各加一；登记读数不改变工单版本';
COMMENT ON COLUMN work_order.status IS '工单状态：CREATED 未开始 / IN_PROGRESS 进行中 / CLOSED 已关闭 / CANCELLED 已取消 / TERMINATED 已终止';
COMMENT ON COLUMN work_order.baseline_reading_id IS '基线读数标识（建单时冻结，须为当前已认证读数）';
COMMENT ON COLUMN work_order.baseline_revision_no IS '基线读数建单时修订号（快照，不随后续修订变化）';
COMMENT ON COLUMN work_order.baseline_sampled_at IS '基线读数采样时刻（UTC 快照）';
COMMENT ON COLUMN work_order.baseline_cumulative_minutes IS '基线读数累计工时（分钟，快照）';
COMMENT ON COLUMN work_order.window_start IS '允许登记窗口起点（UTC，含）';
COMMENT ON COLUMN work_order.window_end IS '允许登记窗口终点（UTC，不含），严格晚于起点';
COMMENT ON COLUMN work_order.last_valid_reading_id IS '工单期内最近有效读数标识；无新读数时为基线读数，null 表示尚未回填';
COMMENT ON COLUMN work_order.last_valid_sampled_at IS '最近有效读数采样时刻（UTC）';
COMMENT ON COLUMN work_order.last_valid_cumulative_minutes IS '最近有效读数累计工时（分钟）';
COMMENT ON COLUMN work_order.last_valid_revision_no IS '最近有效读数修订号';
COMMENT ON COLUMN work_order.created_at IS '建单时刻（UTC）';
COMMENT ON COLUMN work_order.started_at IS '开始时刻（UTC），未开始为 null';
COMMENT ON COLUMN work_order.closed_at IS '关闭时刻（UTC），未关闭为 null';
COMMENT ON COLUMN work_order.cancelled_at IS '取消时刻（UTC），未取消为 null';
COMMENT ON COLUMN work_order.terminated_at IS '终止时刻（UTC），未终止为 null';
COMMENT ON COLUMN work_order.terminate_reason IS '终止原因，未终止为 null';

-- 工单关闭快照：关闭时写入，之后不可变；读数新增与修订不会改写快照。
CREATE TABLE IF NOT EXISTS maintenance_snapshot (
    snapshot_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    work_order_id VARCHAR(64) NOT NULL,
    equipment_id VARCHAR(64) NOT NULL,
    baseline_reading_id VARCHAR(64) NOT NULL,
    baseline_revision_no INT NOT NULL,
    baseline_sampled_at TIMESTAMP WITH TIME ZONE NOT NULL,
    baseline_cumulative_minutes BIGINT NOT NULL,
    last_valid_reading_id VARCHAR(64) NOT NULL,
    last_valid_revision_no INT NOT NULL,
    last_valid_sampled_at TIMESTAMP WITH TIME ZONE NOT NULL,
    last_valid_cumulative_minutes BIGINT NOT NULL,
    closed_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_snapshot_work_order UNIQUE (equipment_id, work_order_id)
);
COMMENT ON TABLE maintenance_snapshot IS '工单关闭不可变快照：基线、最后有效读数与关闭时刻，关闭后任何读数变更不影响本快照';
COMMENT ON COLUMN maintenance_snapshot.snapshot_id IS '快照自增主键';
COMMENT ON COLUMN maintenance_snapshot.work_order_id IS '所属工单标识';
COMMENT ON COLUMN maintenance_snapshot.equipment_id IS '所属设备标识';
COMMENT ON COLUMN maintenance_snapshot.baseline_reading_id IS '基线读数标识';
COMMENT ON COLUMN maintenance_snapshot.baseline_revision_no IS '基线读数修订号';
COMMENT ON COLUMN maintenance_snapshot.baseline_sampled_at IS '基线读数采样时刻（UTC）';
COMMENT ON COLUMN maintenance_snapshot.baseline_cumulative_minutes IS '基线读数累计工时（分钟）';
COMMENT ON COLUMN maintenance_snapshot.last_valid_reading_id IS '最后有效读数标识（无新读数时为基线读数）';
COMMENT ON COLUMN maintenance_snapshot.last_valid_revision_no IS '最后有效读数修订号';
COMMENT ON COLUMN maintenance_snapshot.last_valid_sampled_at IS '最后有效读数采样时刻（UTC）';
COMMENT ON COLUMN maintenance_snapshot.last_valid_cumulative_minutes IS '最后有效读数累计工时（分钟）';
COMMENT ON COLUMN maintenance_snapshot.closed_at IS '工单关闭时刻（UTC）';

-- 工单操作幂等去重：workOrderKey 全局唯一；指纹含工单版本、设备、基线、窗口和读数摘要。
CREATE TABLE IF NOT EXISTS work_order_idempotency (
    work_order_key VARCHAR(128) NOT NULL PRIMARY KEY,
    operation VARCHAR(48) NOT NULL,
    request_fingerprint VARCHAR(2048) NOT NULL,
    response_body CLOB NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);
COMMENT ON TABLE work_order_idempotency IS '工单操作幂等：同键同参重放原成功结果，同键异参返回 409，失败回滚不占键';
COMMENT ON COLUMN work_order_idempotency.work_order_key IS '工单操作幂等键（客户端提供）';
COMMENT ON COLUMN work_order_idempotency.operation IS '操作类型（建单/开始/登记读数/关闭/取消/终止）';
COMMENT ON COLUMN work_order_idempotency.request_fingerprint IS '指纹：工单版本、设备、基线、窗口与读数摘要';
COMMENT ON COLUMN work_order_idempotency.response_body IS '原成功响应报文（JSON），重放时原样返回';
COMMENT ON COLUMN work_order_idempotency.created_at IS '首次成功处理时刻（UTC）';
