-- 设备工时保养判定：H2（MODE=MySQL）自动建表脚本。
-- 所有时刻字段均为 UTC（TIMESTAMP WITH TIME ZONE），分钟数为非负整数。

-- 设备主表：每台设备一行，版本号用于写操作乐观并发控制。
CREATE TABLE IF NOT EXISTS equipment (
    equipment_id VARCHAR(64) NOT NULL PRIMARY KEY,
    maintenance_period_minutes BIGINT NOT NULL,
    version BIGINT NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);
COMMENT ON TABLE equipment IS '设备主表：每台设备一行';
COMMENT ON COLUMN equipment.equipment_id IS '设备唯一标识（客户端提供）';
COMMENT ON COLUMN equipment.maintenance_period_minutes IS '保养周期（分钟），正整数，登记后不可修改';
COMMENT ON COLUMN equipment.version IS '设备版本号，初始 1；新增读数/修订/完成保养均校验 expectedVersion 并加一';
COMMENT ON COLUMN equipment.created_at IS '登记时刻（UTC）';

-- 工时读数当前值表：reading_id 设备内唯一，同设备同一采样时刻仅一条。
CREATE TABLE IF NOT EXISTS reading (
    equipment_id VARCHAR(64) NOT NULL,
    reading_id VARCHAR(64) NOT NULL,
    sampled_at TIMESTAMP WITH TIME ZONE NOT NULL,
    cumulative_minutes BIGINT NOT NULL,
    revision_no INT NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    PRIMARY KEY (equipment_id, reading_id),
    CONSTRAINT uq_reading_sampled_at UNIQUE (equipment_id, sampled_at)
);
COMMENT ON TABLE reading IS '工时读数当前值：按采样时刻排序后累计分钟须单调不减';
COMMENT ON COLUMN reading.equipment_id IS '所属设备标识';
COMMENT ON COLUMN reading.reading_id IS '读数标识，设备内唯一';
COMMENT ON COLUMN reading.sampled_at IS 'UTC 采样时刻；同设备同一时刻仅允许一条读数';
COMMENT ON COLUMN reading.cumulative_minutes IS '当前累计工时（分钟），非负整数，随修订更新';
COMMENT ON COLUMN reading.revision_no IS '当前修订号，初始 1，每次修订加一';
COMMENT ON COLUMN reading.created_at IS '读数登记时刻（UTC）';
COMMENT ON COLUMN reading.updated_at IS '最近一次修订时刻（UTC）';

-- 读数修订历史：每次修订追加一行，保留全部历史值。
CREATE TABLE IF NOT EXISTS reading_revision (
    equipment_id VARCHAR(64) NOT NULL,
    reading_id VARCHAR(64) NOT NULL,
    revision_no INT NOT NULL,
    cumulative_minutes BIGINT NOT NULL,
    request_id VARCHAR(128) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    PRIMARY KEY (equipment_id, reading_id, revision_no)
);
COMMENT ON TABLE reading_revision IS '读数修订历史：revision_no=1 为初始登记值，其后每行对应一次修订';
COMMENT ON COLUMN reading_revision.equipment_id IS '所属设备标识';
COMMENT ON COLUMN reading_revision.reading_id IS '读数标识';
COMMENT ON COLUMN reading_revision.revision_no IS '修订号，从 1 开始递增';
COMMENT ON COLUMN reading_revision.cumulative_minutes IS '该修订版本的累计工时（分钟）';
COMMENT ON COLUMN reading_revision.request_id IS '产生该修订的请求 requestId';
COMMENT ON COLUMN reading_revision.created_at IS '该修订生效时刻（UTC）';

-- 保养记录：锚定某读数的特定修订号，保存锚点时刻与工时快照，不允许删除。
CREATE TABLE IF NOT EXISTS maintenance (
    maintenance_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    equipment_id VARCHAR(64) NOT NULL,
    reading_id VARCHAR(64) NOT NULL,
    anchor_revision_no INT NOT NULL,
    anchor_sampled_at TIMESTAMP WITH TIME ZONE NOT NULL,
    anchor_cumulative_minutes BIGINT NOT NULL,
    request_id VARCHAR(128) NOT NULL,
    completed_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_maintenance_equipment ON maintenance (equipment_id, anchor_sampled_at);
COMMENT ON TABLE maintenance IS '保养记录：锚点时间须严格晚于上次保养锚点；作为锚点的读数不可再修订';
COMMENT ON COLUMN maintenance.maintenance_id IS '保养记录自增主键';
COMMENT ON COLUMN maintenance.equipment_id IS '所属设备标识';
COMMENT ON COLUMN maintenance.reading_id IS '锚点读数标识';
COMMENT ON COLUMN maintenance.anchor_revision_no IS '锚点读数在保养完成时的修订号';
COMMENT ON COLUMN maintenance.anchor_sampled_at IS '锚点读数的 UTC 采样时刻（快照）';
COMMENT ON COLUMN maintenance.anchor_cumulative_minutes IS '锚点读数在保养完成时的累计工时快照（分钟）';
COMMENT ON COLUMN maintenance.request_id IS '完成保养请求的 requestId';
COMMENT ON COLUMN maintenance.completed_at IS '保养完成登记时刻（UTC）';

-- 幂等去重表：requestId 全局唯一；仅成功结果占键，失败回滚不占键。
CREATE TABLE IF NOT EXISTS idempotency_request (
    request_id VARCHAR(128) NOT NULL PRIMARY KEY,
    operation VARCHAR(48) NOT NULL,
    request_fingerprint CLOB NOT NULL,
    response_body CLOB NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);
COMMENT ON TABLE idempotency_request IS '写操作幂等去重：同键同参重放原成功结果，同键异参返回 409';
COMMENT ON COLUMN idempotency_request.request_id IS '全局唯一请求标识';
COMMENT ON COLUMN idempotency_request.operation IS '操作类型（登记设备/新增读数/修订/完成保养）';
COMMENT ON COLUMN idempotency_request.request_fingerprint IS '业务参数指纹（不含 requestId，规范化 JSON），用于同键异参判定';
COMMENT ON COLUMN idempotency_request.response_body IS '原成功响应报文（JSON），重放时原样返回';
COMMENT ON COLUMN idempotency_request.created_at IS '首次成功处理时刻（UTC）';

-- ========== 设备能源隔离 ==========
-- 所有时刻均为 UTC；隔离生效区间按左闭右开 [activated_at, released_at) 解释。

-- 能源隔离令：PENDING（待确认）→ ACTIVE（全部锁定点各获两名不同角色确认，隔离生效）→ RELEASED（全部锁定点逐一解除并登记原因）。
CREATE TABLE IF NOT EXISTS isolation_order (
    order_id VARCHAR(64) NOT NULL PRIMARY KEY,
    equipment_id VARCHAR(64) NOT NULL,
    status VARCHAR(16) NOT NULL,
    created_by VARCHAR(64) NOT NULL,
    request_id VARCHAR(128) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    activated_at TIMESTAMP WITH TIME ZONE,
    activated_by VARCHAR(64),
    activated_request_id VARCHAR(128),
    released_at TIMESTAMP WITH TIME ZONE,
    released_by VARCHAR(64),
    release_reason CLOB,
    release_request_id VARCHAR(128)
);
CREATE INDEX IF NOT EXISTS idx_isolation_order_equipment
    ON isolation_order (equipment_id, created_at, order_id);
COMMENT ON TABLE isolation_order IS '能源隔离令：每台设备同时只允许一个未解除（PENDING/ACTIVE）的隔离令';
COMMENT ON COLUMN isolation_order.order_id IS '隔离令唯一标识（客户端提供，全局唯一）';
COMMENT ON COLUMN isolation_order.equipment_id IS '被隔离设备标识';
COMMENT ON COLUMN isolation_order.status IS '状态：PENDING 待确认 / ACTIVE 隔离生效 / RELEASED 已解除';
COMMENT ON COLUMN isolation_order.created_by IS '创建隔离令的操作者标识（固化业务证据）';
COMMENT ON COLUMN isolation_order.request_id IS '创建隔离令请求的 requestId';
COMMENT ON COLUMN isolation_order.created_at IS '隔离令创建时刻（UTC）';
COMMENT ON COLUMN isolation_order.activated_at IS '隔离生效时刻（UTC）；未生效为 null';
COMMENT ON COLUMN isolation_order.activated_by IS '触发隔离生效（最后一个集齐确认）的操作者；未生效为 null';
COMMENT ON COLUMN isolation_order.activated_request_id IS '触发隔离生效的确认请求 requestId；未生效为 null';
COMMENT ON COLUMN isolation_order.released_at IS '解除完成时刻（UTC，区间右端点，开区间）；未解除为 null';
COMMENT ON COLUMN isolation_order.released_by IS '提交解除请求的操作者标识；未解除为 null';
COMMENT ON COLUMN isolation_order.release_reason IS '解除原因（必填），未解除为 null';
COMMENT ON COLUMN isolation_order.release_request_id IS '解除请求的 requestId；未解除为 null';

-- 隔离令锁定点：创建时固化，后续任何操作不得改写。
CREATE TABLE IF NOT EXISTS isolation_lock_point (
    order_id VARCHAR(64) NOT NULL,
    lock_point_id VARCHAR(64) NOT NULL,
    ordinal INT NOT NULL,
    lock_point_name VARCHAR(255),
    PRIMARY KEY (order_id, lock_point_id)
);
COMMENT ON TABLE isolation_lock_point IS '隔离令锁定点集合：创建时一次性固化，重复锁定点在创建时即被拒绝（422）';
COMMENT ON COLUMN isolation_lock_point.order_id IS '所属隔离令标识';
COMMENT ON COLUMN isolation_lock_point.lock_point_id IS '锁定点标识，隔离令内唯一';
COMMENT ON COLUMN isolation_lock_point.ordinal IS '提交序号（从 0 起），用于明细稳定排序';
COMMENT ON COLUMN isolation_lock_point.lock_point_name IS '锁定点名称/位置描述，可为 null';

-- 锁定点确认：每个锁定点须两名不同维护角色各确认一次；同角色重复确认 422。
CREATE TABLE IF NOT EXISTS isolation_confirmation (
    confirmation_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id VARCHAR(64) NOT NULL,
    lock_point_id VARCHAR(64) NOT NULL,
    operator_id VARCHAR(64) NOT NULL,
    role_id VARCHAR(64) NOT NULL,
    request_id VARCHAR(128) NOT NULL,
    confirmed_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_isolation_confirmation_role
    ON isolation_confirmation (order_id, lock_point_id, role_id);
CREATE INDEX IF NOT EXISTS idx_isolation_confirmation_order
    ON isolation_confirmation (order_id, confirmed_at, confirmation_id);
COMMENT ON TABLE isolation_confirmation IS '锁定点确认记录：同一锁定点同一角色仅允许确认一次（追加，不可改写）';
COMMENT ON COLUMN isolation_confirmation.confirmation_id IS '确认记录自增主键';
COMMENT ON COLUMN isolation_confirmation.order_id IS '所属隔离令标识';
COMMENT ON COLUMN isolation_confirmation.lock_point_id IS '被确认的锁定点标识';
COMMENT ON COLUMN isolation_confirmation.operator_id IS '执行确认的维护人员标识（操作人）';
COMMENT ON COLUMN isolation_confirmation.role_id IS '维护角色标识；同一锁定点须两名不同角色确认';
COMMENT ON COLUMN isolation_confirmation.request_id IS '确认请求的 requestId';
COMMENT ON COLUMN isolation_confirmation.confirmed_at IS '确认生效时刻（UTC）';

-- 锁定点解除：解除隔离时必须与创建时锁定点集合逐一完全匹配，部分解除 422。
CREATE TABLE IF NOT EXISTS isolation_lock_release (
    order_id VARCHAR(64) NOT NULL,
    lock_point_id VARCHAR(64) NOT NULL,
    operator_id VARCHAR(64) NOT NULL,
    request_id VARCHAR(128) NOT NULL,
    released_at TIMESTAMP WITH TIME ZONE NOT NULL,
    PRIMARY KEY (order_id, lock_point_id)
);
COMMENT ON TABLE isolation_lock_release IS '锁定点解除记录：随隔离解除一次性写入，缺失/多余/重复均导致整批解除失败';
COMMENT ON COLUMN isolation_lock_release.order_id IS '所属隔离令标识';
COMMENT ON COLUMN isolation_lock_release.lock_point_id IS '被解除的锁定点标识';
COMMENT ON COLUMN isolation_lock_release.operator_id IS '执行该锁定点解除确认的操作人';
COMMENT ON COLUMN isolation_lock_release.request_id IS '解除请求的 requestId';
COMMENT ON COLUMN isolation_lock_release.released_at IS '解除登记时刻（UTC）';

-- 隔离生效期间被拒绝的新增读数：固化当时锁定点集合快照与提交操作人，作为业务证据不可改写。
CREATE TABLE IF NOT EXISTS isolated_reading_rejection (
    rejection_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    equipment_id VARCHAR(64) NOT NULL,
    order_id VARCHAR(64) NOT NULL,
    reading_id VARCHAR(64) NOT NULL,
    operator_id VARCHAR(64),
    request_id VARCHAR(128) NOT NULL,
    sampled_at TIMESTAMP WITH TIME ZONE NOT NULL,
    cumulative_minutes BIGINT NOT NULL,
    lock_point_count INT NOT NULL,
    lock_point_snapshot CLOB NOT NULL,
    rejected_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_isolated_rejection_equipment
    ON isolated_reading_rejection (equipment_id, rejected_at, rejection_id);
CREATE INDEX IF NOT EXISTS idx_isolated_rejection_order
    ON isolated_reading_rejection (order_id);
COMMENT ON TABLE isolated_reading_rejection IS '隔离生效期被拒新增读数证据：读数事务回滚但本表在独立事务中固化，失败不占幂等键';
COMMENT ON COLUMN isolated_reading_rejection.rejection_id IS '拒绝记录自增主键';
COMMENT ON COLUMN isolated_reading_rejection.equipment_id IS '读数目标设备标识';
COMMENT ON COLUMN isolated_reading_rejection.order_id IS '当时生效的隔离令标识';
COMMENT ON COLUMN isolated_reading_rejection.reading_id IS '被拒读数标识';
COMMENT ON COLUMN isolated_reading_rejection.operator_id IS '提交读数的操作人；请求未提供时为 null';
COMMENT ON COLUMN isolated_reading_rejection.request_id IS '被拒读数请求的 requestId（失败不占键，可被后续请求复用）';
COMMENT ON COLUMN isolated_reading_rejection.sampled_at IS '被拒读数声称的 UTC 采样时刻';
COMMENT ON COLUMN isolated_reading_rejection.cumulative_minutes IS '被拒读数声称的累计工时（分钟）';
COMMENT ON COLUMN isolated_reading_rejection.lock_point_count IS '拒绝时刻隔离令锁定点数量（实际值快照）';
COMMENT ON COLUMN isolated_reading_rejection.lock_point_snapshot IS '拒绝时刻锁定点标识集合 JSON 快照（排序后固化）';
COMMENT ON COLUMN isolated_reading_rejection.rejected_at IS '拒绝发生时刻（UTC）';
