-- 设备工时保养判定：H2（MODE=MySQL）自动建表脚本。
-- 所有时刻字段均为 UTC（TIMESTAMP WITH TIME ZONE），分钟数为非负整数。

-- 设备主表：每台设备一行，版本号用于写操作乐观并发控制。
CREATE TABLE IF NOT EXISTS equipment (
    equipment_id VARCHAR(64) NOT NULL PRIMARY KEY,
    maintenance_period_minutes BIGINT NOT NULL,
    version BIGINT NOT NULL,
    state VARCHAR(24) NOT NULL,
    decommissioned_at TIMESTAMP WITH TIME ZONE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);
COMMENT ON TABLE equipment IS '设备主表：每台设备一行';
COMMENT ON COLUMN equipment.equipment_id IS '设备唯一标识（客户端提供）';
COMMENT ON COLUMN equipment.maintenance_period_minutes IS '保养周期（分钟），正整数，登记后不可修改';
COMMENT ON COLUMN equipment.version IS '设备版本号，初始 1；新增读数/修订/完成保养/隔离相关写操作均校验 expectedVersion 并加一';
COMMENT ON COLUMN equipment.state IS '设备状态：ACTIVE 在用；DECOMMISSIONED 已停用，停用后不可创建隔离令';
COMMENT ON COLUMN equipment.decommissioned_at IS '停用时刻（UTC）；在用时为 null';
COMMENT ON COLUMN equipment.created_at IS '登记时刻（UTC）';

-- 工时读数当前值表：reading_id 设备内唯一，同设备同一采样时刻仅一条。
CREATE TABLE IF NOT EXISTS reading (
    equipment_id VARCHAR(64) NOT NULL,
    reading_id VARCHAR(64) NOT NULL,
    sampled_at TIMESTAMP WITH TIME ZONE NOT NULL,
    cumulative_minutes BIGINT NOT NULL,
    revision_no INT NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    PRIMARY KEY (equipment_id, reading_id),
    CONSTRAINT uq_reading_sampled_at UNIQUE (equipment_id, sampled_at)
);
COMMENT ON TABLE reading IS '工时读数当前值：按采样时刻排序后累计分钟须单调不减';
COMMENT ON COLUMN reading.equipment_id IS '所属设备标识';
COMMENT ON COLUMN reading.reading_id IS '读数标识，设备内唯一';
COMMENT ON COLUMN reading.sampled_at IS 'UTC 采样时刻；同设备同一时刻仅允许一条读数';
COMMENT ON COLUMN reading.cumulative_minutes IS '当前累计工时（分钟），非负整数，随修订更新';
COMMENT ON COLUMN reading.revision_no IS '当前修订号，初始 1，每次修订加一';
COMMENT ON COLUMN reading.created_at IS '读数登记时刻（UTC）';
COMMENT ON COLUMN reading.updated_at IS '最近一次修订时刻（UTC）';

-- 读数修订历史：每次修订追加一行，保留全部历史值。
CREATE TABLE IF NOT EXISTS reading_revision (
    equipment_id VARCHAR(64) NOT NULL,
    reading_id VARCHAR(64) NOT NULL,
    revision_no INT NOT NULL,
    cumulative_minutes BIGINT NOT NULL,
    request_id VARCHAR(128) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    PRIMARY KEY (equipment_id, reading_id, revision_no)
);
COMMENT ON TABLE reading_revision IS '读数修订历史：revision_no=1 为初始登记值，其后每行对应一次修订';
COMMENT ON COLUMN reading_revision.equipment_id IS '所属设备标识';
COMMENT ON COLUMN reading_revision.reading_id IS '读数标识';
COMMENT ON COLUMN reading_revision.revision_no IS '修订号，从 1 开始递增';
COMMENT ON COLUMN reading_revision.cumulative_minutes IS '该修订版本的累计工时（分钟）';
COMMENT ON COLUMN reading_revision.request_id IS '产生该修订的请求 requestId';
COMMENT ON COLUMN reading_revision.created_at IS '该修订生效时刻（UTC）';

-- 保养记录：锚定某读数的特定修订号，保存锚点时刻与工时快照，不允许删除。
CREATE TABLE IF NOT EXISTS maintenance (
    maintenance_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    equipment_id VARCHAR(64) NOT NULL,
    reading_id VARCHAR(64) NOT NULL,
    anchor_revision_no INT NOT NULL,
    anchor_sampled_at TIMESTAMP WITH TIME ZONE NOT NULL,
    anchor_cumulative_minutes BIGINT NOT NULL,
    request_id VARCHAR(128) NOT NULL,
    completed_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_maintenance_equipment ON maintenance (equipment_id, anchor_sampled_at);
COMMENT ON TABLE maintenance IS '保养记录：锚点时间须严格晚于上次保养锚点；作为锚点的读数不可再修订';
COMMENT ON COLUMN maintenance.maintenance_id IS '保养记录自增主键';
COMMENT ON COLUMN maintenance.equipment_id IS '所属设备标识';
COMMENT ON COLUMN maintenance.reading_id IS '锚点读数标识';
COMMENT ON COLUMN maintenance.anchor_revision_no IS '锚点读数在保养完成时的修订号';
COMMENT ON COLUMN maintenance.anchor_sampled_at IS '锚点读数的 UTC 采样时刻（快照）';
COMMENT ON COLUMN maintenance.anchor_cumulative_minutes IS '锚点读数在保养完成时的累计工时快照（分钟）';
COMMENT ON COLUMN maintenance.request_id IS '完成保养请求的 requestId';
COMMENT ON COLUMN maintenance.completed_at IS '保养完成登记时刻（UTC）';

-- 能源隔离令：一台设备同一时刻至多一条未解除（PENDING/ACTIVE）隔离令，由业务在行锁下保证。
CREATE TABLE IF NOT EXISTS isolation_order (
    isolation_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    equipment_id VARCHAR(64) NOT NULL,
    state VARCHAR(16) NOT NULL,
    created_by VARCHAR(64) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    effective_at TIMESTAMP WITH TIME ZONE,
    released_at TIMESTAMP WITH TIME ZONE,
    release_reason CLOB,
    released_by VARCHAR(64)
);
CREATE INDEX IF NOT EXISTS idx_isolation_equipment ON isolation_order (equipment_id, created_at, isolation_id);
CREATE INDEX IF NOT EXISTS idx_isolation_state ON isolation_order (equipment_id, state);
COMMENT ON TABLE isolation_order IS '能源隔离令：PENDING 待双角色确认；ACTIVE 生效（左闭右开 [effective_at, released_at)）；RELEASED 全部锁定点逐一解除';
COMMENT ON COLUMN isolation_order.isolation_id IS '隔离令自增主键';
COMMENT ON COLUMN isolation_order.equipment_id IS '所属设备标识';
COMMENT ON COLUMN isolation_order.state IS '状态：PENDING / ACTIVE / RELEASED';
COMMENT ON COLUMN isolation_order.created_by IS '创建操作人（固化）';
COMMENT ON COLUMN isolation_order.created_at IS '隔离令创建时刻（UTC）';
COMMENT ON COLUMN isolation_order.effective_at IS '生效时刻（UTC，第二名角色确认时刻）；PENDING 时为 null';
COMMENT ON COLUMN isolation_order.released_at IS '解除完成时刻（UTC）；未完成解除时为 null';
COMMENT ON COLUMN isolation_order.release_reason IS '解除原因快照（逐点原因的规范化 JSON）；未解除为 null';
COMMENT ON COLUMN isolation_order.released_by IS '解除完成登记操作人；未解除为 null';

-- 隔离锁定点：随隔离令创建并固化；逐一解除时登记原因、解除时刻与操作人。
CREATE TABLE IF NOT EXISTS isolation_lock_point (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    isolation_id BIGINT NOT NULL,
    lock_point_id VARCHAR(96) NOT NULL,
    label VARCHAR(200),
    seq_no INT NOT NULL,
    release_reason CLOB,
    locked_at TIMESTAMP WITH TIME ZONE NOT NULL,
    released_at TIMESTAMP WITH TIME ZONE,
    released_by VARCHAR(64),
    CONSTRAINT uq_isolation_lock_point UNIQUE (isolation_id, lock_point_id)
);
CREATE INDEX IF NOT EXISTS idx_lock_point_isolation ON isolation_lock_point (isolation_id, seq_no);
COMMENT ON TABLE isolation_lock_point IS '隔离锁定点：创建时固化完整集合，解除时逐一登记，解除后不可改写';
COMMENT ON COLUMN isolation_lock_point.isolation_id IS '所属隔离令标识';
COMMENT ON COLUMN isolation_lock_point.lock_point_id IS '锁定点业务标识，隔离令内唯一，重复返回 422';
COMMENT ON COLUMN isolation_lock_point.label IS '锁定点名称；调用方未提供时为 null';
COMMENT ON COLUMN isolation_lock_point.seq_no IS '创建顺序号，从 1 开始，用于稳定排序';
COMMENT ON COLUMN isolation_lock_point.release_reason IS '该锁定点解除原因；未解除为 null';
COMMENT ON COLUMN isolation_lock_point.locked_at IS '锁定登记时刻（UTC，随隔离令创建）';
COMMENT ON COLUMN isolation_lock_point.released_at IS '解除时刻（UTC）；未解除为 null';
COMMENT ON COLUMN isolation_lock_point.released_by IS '解除操作人；未解除为 null';

-- 隔离确认：两名不同维护角色各一行，角色在隔离令内唯一。
CREATE TABLE IF NOT EXISTS isolation_confirmation (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    isolation_id BIGINT NOT NULL,
    operator_id VARCHAR(64) NOT NULL,
    role VARCHAR(64) NOT NULL,
    request_id VARCHAR(128) NOT NULL,
    seq_no INT NOT NULL,
    confirmed_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_isolation_role UNIQUE (isolation_id, role)
);
CREATE INDEX IF NOT EXISTS idx_confirmation_isolation ON isolation_confirmation (isolation_id, seq_no);
COMMENT ON TABLE isolation_confirmation IS '隔离确认记录：两名不同维护角色分别确认；同一角色重复确认返回 422';
COMMENT ON COLUMN isolation_confirmation.isolation_id IS '所属隔离令标识';
COMMENT ON COLUMN isolation_confirmation.operator_id IS '确认操作人（固化）';
COMMENT ON COLUMN isolation_confirmation.role IS '维护角色；同一隔离令内两名确认人角色不可相同';
COMMENT ON COLUMN isolation_confirmation.request_id IS '确认请求 requestId';
COMMENT ON COLUMN isolation_confirmation.seq_no IS '确认顺序号（1 第一名角色，2 第二名角色）';
COMMENT ON COLUMN isolation_confirmation.confirmed_at IS '确认时刻（UTC）';

-- 隔离生效期间被拒的新增读数：固化当时隔离令锁定点集合与提交操作人，仅追加不可改写。
CREATE TABLE IF NOT EXISTS rejected_reading (
    rejected_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    equipment_id VARCHAR(64) NOT NULL,
    isolation_id BIGINT NOT NULL,
    reading_id VARCHAR(64) NOT NULL,
    sampled_at TIMESTAMP WITH TIME ZONE NOT NULL,
    cumulative_minutes BIGINT NOT NULL,
    operator_id VARCHAR(64),
    request_id VARCHAR(128),
    lock_points_json CLOB NOT NULL,
    rejected_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_rejected_equipment ON rejected_reading (equipment_id, rejected_at, rejected_id);
COMMENT ON TABLE rejected_reading IS '隔离生效期间被拒新增读数的诊断证据：仅追加，不随隔离解除或读数重提而改写';
COMMENT ON COLUMN rejected_reading.equipment_id IS '提交读数的设备标识';
COMMENT ON COLUMN rejected_reading.isolation_id IS '拒绝时生效的隔离令标识';
COMMENT ON COLUMN rejected_reading.reading_id IS '被拒读数标识';
COMMENT ON COLUMN rejected_reading.sampled_at IS '被拒读数的 UTC 采样时刻';
COMMENT ON COLUMN rejected_reading.cumulative_minutes IS '被拒读数的累计工时（分钟）';
COMMENT ON COLUMN rejected_reading.operator_id IS '提交操作人；请求未提供时为 null';
COMMENT ON COLUMN rejected_reading.request_id IS '提交请求 requestId；请求未提供时为 null';
COMMENT ON COLUMN rejected_reading.lock_points_json IS '拒绝时隔离令锁定点标识集合的规范化 JSON 快照';
COMMENT ON COLUMN rejected_reading.rejected_at IS '拒绝时刻（UTC）';

-- 幂等去重表：requestId 全局唯一；仅成功结果占键，失败回滚不占键。
CREATE TABLE IF NOT EXISTS idempotency_request (
    request_id VARCHAR(128) NOT NULL PRIMARY KEY,
    operation VARCHAR(48) NOT NULL,
    request_fingerprint CLOB NOT NULL,
    response_body CLOB NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);
COMMENT ON TABLE idempotency_request IS '写操作幂等去重：同键同参重放原成功结果，同键异参返回 409';
COMMENT ON COLUMN idempotency_request.request_id IS '全局唯一请求标识';
COMMENT ON COLUMN idempotency_request.operation IS '操作类型（登记设备/新增读数/修订/完成保养）';
COMMENT ON COLUMN idempotency_request.request_fingerprint IS '业务参数指纹（不含 requestId），用于同键异参判定';
COMMENT ON COLUMN idempotency_request.response_body IS '原成功响应报文（JSON），重放时原样返回';
COMMENT ON COLUMN idempotency_request.created_at IS '首次成功处理时刻（UTC）';
