-- 设备工时保养判定与保养证据包：H2（MODE=MySQL）自动建表脚本。
-- 所有时刻字段均为 UTC（TIMESTAMP WITH TIME ZONE），分钟数为非负整数。
-- 时间区间一律左闭右开：周期起点等于上次保养锚点时刻，下一周期锚点必须严格晚于该起点。

-- 设备主表：每台设备一行，版本号用于写操作乐观并发控制。
CREATE TABLE IF NOT EXISTS equipment (
    equipment_id VARCHAR(64) NOT NULL PRIMARY KEY,
    maintenance_period_minutes BIGINT NOT NULL,
    overdue_threshold_minutes BIGINT,
    version BIGINT NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);
COMMENT ON TABLE equipment IS '设备主表：每台设备一行';
COMMENT ON COLUMN equipment.equipment_id IS '设备唯一标识（客户端提供）';
COMMENT ON COLUMN equipment.maintenance_period_minutes IS '保养周期（分钟），正整数，登记后不可修改；本轮运行分钟达到该值为 DUE';
COMMENT ON COLUMN equipment.overdue_threshold_minutes IS '逾期阈值（分钟），可空；非空时须大于保养周期，本轮运行分钟达到该值为 OVERDUE，null 表示不判定 OVERDUE';
COMMENT ON COLUMN equipment.version IS '设备版本号，初始 1；新增读数/修订/模板修订/证据提交/完成保养均校验 expectedVersion 并加一';
COMMENT ON COLUMN equipment.created_at IS '登记时刻（UTC）';

-- 工时读数当前值表：reading_id 设备内唯一，同设备同一采样时刻仅一条。
CREATE TABLE IF NOT EXISTS reading (
    equipment_id VARCHAR(64) NOT NULL,
    reading_id VARCHAR(64) NOT NULL,
    sampled_at TIMESTAMP WITH TIME ZONE NOT NULL,
    cumulative_minutes BIGINT NOT NULL,
    revision_no INT NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    PRIMARY KEY (equipment_id, reading_id),
    CONSTRAINT uq_reading_sampled_at UNIQUE (equipment_id, sampled_at)
);
COMMENT ON TABLE reading IS '工时读数当前值：按采样时刻排序后累计分钟须单调不减';
COMMENT ON COLUMN reading.equipment_id IS '所属设备标识';
COMMENT ON COLUMN reading.reading_id IS '读数标识，设备内唯一';
COMMENT ON COLUMN reading.sampled_at IS 'UTC 采样时刻；同设备同一时刻仅允许一条读数';
COMMENT ON COLUMN reading.cumulative_minutes IS '当前累计工时（分钟），非负整数，随修订更新';
COMMENT ON COLUMN reading.revision_no IS '当前修订号，初始 1，每次修订加一';
COMMENT ON COLUMN reading.created_at IS '读数登记时刻（UTC）';
COMMENT ON COLUMN reading.updated_at IS '最近一次修订时刻（UTC）';

-- 读数修订历史：每次修订追加一行，保留全部历史值。
CREATE TABLE IF NOT EXISTS reading_revision (
    equipment_id VARCHAR(64) NOT NULL,
    reading_id VARCHAR(64) NOT NULL,
    revision_no INT NOT NULL,
    cumulative_minutes BIGINT NOT NULL,
    request_id VARCHAR(128) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    PRIMARY KEY (equipment_id, reading_id, revision_no)
);
COMMENT ON TABLE reading_revision IS '读数修订历史：revision_no=1 为初始登记值，其后每行对应一次修订';
COMMENT ON COLUMN reading_revision.equipment_id IS '所属设备标识';
COMMENT ON COLUMN reading_revision.reading_id IS '读数标识';
COMMENT ON COLUMN reading_revision.revision_no IS '修订号，从 1 开始递增';
COMMENT ON COLUMN reading_revision.cumulative_minutes IS '该修订版本的累计工时（分钟）';
COMMENT ON COLUMN reading_revision.request_id IS '产生该修订的请求 requestId';
COMMENT ON COLUMN reading_revision.created_at IS '该修订生效时刻（UTC）';

-- 保养周期：设备登记即创建周期 1；每次双人确认完工后当前周期置 COMPLETED 并开启下一周期。
CREATE TABLE IF NOT EXISTS maintenance_cycle (
    cycle_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    equipment_id VARCHAR(64) NOT NULL,
    cycle_no INT NOT NULL,
    period_minutes BIGINT NOT NULL,
    status VARCHAR(16) NOT NULL,
    start_anchor_sampled_at TIMESTAMP WITH TIME ZONE,
    start_anchor_cumulative_minutes BIGINT NOT NULL,
    current_evidence_version INT NOT NULL,
    current_template_version INT,
    completed_at TIMESTAMP WITH TIME ZONE,
    end_anchor_sampled_at TIMESTAMP WITH TIME ZONE,
    end_anchor_cumulative_minutes BIGINT,
    maintenance_id BIGINT,
    CONSTRAINT uq_cycle_no UNIQUE (equipment_id, cycle_no)
);
COMMENT ON TABLE maintenance_cycle IS '保养周期：OPEN 为当前周期，COMPLETED 为已完工不可重开；周期区间左闭右开';
COMMENT ON COLUMN maintenance_cycle.cycle_id IS '周期自增主键';
COMMENT ON COLUMN maintenance_cycle.equipment_id IS '所属设备标识';
COMMENT ON COLUMN maintenance_cycle.cycle_no IS '周期号，设备内从 1 递增';
COMMENT ON COLUMN maintenance_cycle.period_minutes IS '该周期要求的保养周期（分钟），周期创建时由设备快照固化';
COMMENT ON COLUMN maintenance_cycle.status IS '周期状态：OPEN（进行中）/ COMPLETED（已完工，不可变）';
COMMENT ON COLUMN maintenance_cycle.start_anchor_sampled_at IS '周期起点锚点时刻（UTC，等于上次保养锚点）；首周期为 null，表示不设下界';
COMMENT ON COLUMN maintenance_cycle.start_anchor_cumulative_minutes IS '周期起点锚点工时（分钟）；首周期为 0';
COMMENT ON COLUMN maintenance_cycle.current_evidence_version IS '当前周期最新证据包版本号；无证据包时为 0';
COMMENT ON COLUMN maintenance_cycle.current_template_version IS '最新证据包固化时的模板版本；无证据包时为 null';
COMMENT ON COLUMN maintenance_cycle.completed_at IS '完工时刻（UTC）；未完工为 null';
COMMENT ON COLUMN maintenance_cycle.end_anchor_sampled_at IS '完工锚点读数采样时刻（UTC 快照）；未完工为 null';
COMMENT ON COLUMN maintenance_cycle.end_anchor_cumulative_minutes IS '完工锚点读数工时快照（分钟）；未完工为 null';
COMMENT ON COLUMN maintenance_cycle.maintenance_id IS '完工生成的保养记录标识；未完工为 null';

-- 保养模板主表：一台设备一个模板，修订只追加新版本，current_version 指向当前版本。
CREATE TABLE IF NOT EXISTS maintenance_template (
    template_id VARCHAR(64) NOT NULL PRIMARY KEY,
    current_version INT NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL
);
COMMENT ON TABLE maintenance_template IS '保养模板：template_id 等于设备标识；修订产生新版本，旧版本行保留不改写';
COMMENT ON COLUMN maintenance_template.template_id IS '模板标识（等于设备标识）';
COMMENT ON COLUMN maintenance_template.current_version IS '当前模板版本号，从 1 开始，每次修订加一';
COMMENT ON COLUMN maintenance_template.created_at IS '模板首次创建时刻（UTC）';
COMMENT ON COLUMN maintenance_template.updated_at IS '最近一次修订时刻（UTC）';

-- 模板检查项（按版本不可变）：位置顺序即检查结果的规范排序。
CREATE TABLE IF NOT EXISTS maintenance_template_item (
    template_id VARCHAR(64) NOT NULL,
    version INT NOT NULL,
    position INT NOT NULL,
    item_code VARCHAR(64) NOT NULL,
    item_name VARCHAR(128) NOT NULL,
    required BOOLEAN NOT NULL,
    PRIMARY KEY (template_id, version, position),
    CONSTRAINT uq_template_item_code UNIQUE (template_id, version, item_code)
);
COMMENT ON TABLE maintenance_template_item IS '模板检查项版本行：模板修订不改写旧版本行';
COMMENT ON COLUMN maintenance_template_item.template_id IS '所属模板标识';
COMMENT ON COLUMN maintenance_template_item.version IS '模板版本号';
COMMENT ON COLUMN maintenance_template_item.position IS '检查项规范排序位置，从 1 开始，证据结果按此排序';
COMMENT ON COLUMN maintenance_template_item.item_code IS '检查项编码，模板同版本内唯一';
COMMENT ON COLUMN maintenance_template_item.item_name IS '检查项名称';
COMMENT ON COLUMN maintenance_template_item.required IS '是否必检项；仅必检项纳入完工门禁（必须恰有一个 PASS）';

-- 证据包版本：设备同一周期内版本号递增，整包不可变。
CREATE TABLE IF NOT EXISTS evidence_package (
    package_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    equipment_id VARCHAR(64) NOT NULL,
    cycle_no INT NOT NULL,
    package_version INT NOT NULL,
    template_version INT NOT NULL,
    submitted_by VARCHAR(64) NOT NULL,
    submitted_at TIMESTAMP WITH TIME ZONE NOT NULL,
    request_id VARCHAR(128) NOT NULL,
    CONSTRAINT uq_evidence_version UNIQUE (equipment_id, cycle_no, package_version)
);
COMMENT ON TABLE evidence_package IS '保养证据包版本：不可变，版本号周期内递增，固化提交人、模板版本与提交时刻';
COMMENT ON COLUMN evidence_package.package_id IS '证据包自增主键';
COMMENT ON COLUMN evidence_package.equipment_id IS '所属设备标识';
COMMENT ON COLUMN evidence_package.cycle_no IS '所属保养周期号';
COMMENT ON COLUMN evidence_package.package_version IS '证据包版本号，周期内从 1 递增';
COMMENT ON COLUMN evidence_package.template_version IS '提交时设备当前模板版本快照；确认时模板版本变化则 409';
COMMENT ON COLUMN evidence_package.submitted_by IS '证据提交人（维护人员），不可与完工确认人为同一人';
COMMENT ON COLUMN evidence_package.submitted_at IS '证据提交时刻（UTC）';
COMMENT ON COLUMN evidence_package.request_id IS '产生该证据包的请求 requestId';

-- 证据包检查项结果：不可变，按模板 position 规范排序；每个必检项在包内恰有一个结果。
CREATE TABLE IF NOT EXISTS evidence_check_result (
    result_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    equipment_id VARCHAR(64) NOT NULL,
    cycle_no INT NOT NULL,
    package_version INT NOT NULL,
    position INT NOT NULL,
    item_code VARCHAR(64) NOT NULL,
    result VARCHAR(8) NOT NULL,
    note VARCHAR(512),
    CONSTRAINT uq_evidence_result_position UNIQUE (equipment_id, cycle_no, package_version, position),
    CONSTRAINT uq_evidence_result_item UNIQUE (equipment_id, cycle_no, package_version, item_code)
);
COMMENT ON TABLE evidence_check_result IS '证据包检查项结果：不可变；result 取值 PASS/FAIL；note 可空表示无备注';
COMMENT ON COLUMN evidence_check_result.equipment_id IS '所属设备标识';
COMMENT ON COLUMN evidence_check_result.cycle_no IS '所属保养周期号';
COMMENT ON COLUMN evidence_check_result.package_version IS '所属证据包版本号';
COMMENT ON COLUMN evidence_check_result.position IS '规范排序位置，取自提交时模板的 position';
COMMENT ON COLUMN evidence_check_result.item_code IS '检查项编码，必须属于提交时的当前模板版本';
COMMENT ON COLUMN evidence_check_result.result IS '检查结果：PASS 或 FAIL；完工时必检项存在 FAIL 则 422';
COMMENT ON COLUMN evidence_check_result.note IS '检查备注，可空，null 表示无备注';

-- 材料批次登记：撤销只置状态，批次标识与历史引用永不删除。
CREATE TABLE IF NOT EXISTS material (
    material_id VARCHAR(64) NOT NULL PRIMARY KEY,
    material_name VARCHAR(128) NOT NULL,
    unit VARCHAR(16) NOT NULL,
    status VARCHAR(16) NOT NULL,
    registered_at TIMESTAMP WITH TIME ZONE NOT NULL,
    revoked_at TIMESTAMP WITH TIME ZONE,
    revoke_reason VARCHAR(512)
);
COMMENT ON TABLE material IS '材料批次：ACTIVE 可用，REVOKED 已撤销；撤销后已固化的证据摘要不变';
COMMENT ON COLUMN material.material_id IS '材料批次号（客户端提供），全局唯一';
COMMENT ON COLUMN material.material_name IS '材料名称';
COMMENT ON COLUMN material.unit IS '计量单位，登记后不可变';
COMMENT ON COLUMN material.status IS '批次状态：ACTIVE / REVOKED';
COMMENT ON COLUMN material.registered_at IS '登记时刻（UTC）';
COMMENT ON COLUMN material.revoked_at IS '撤销时刻（UTC）；未撤销为 null';
COMMENT ON COLUMN material.revoke_reason IS '撤销原因；未撤销为 null';

-- 证据包材料批次摘要：不可变；同一设备同一周期不可重复引用同一批次（跨证据版本同样禁止）。
CREATE TABLE IF NOT EXISTS evidence_material_summary (
    summary_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    equipment_id VARCHAR(64) NOT NULL,
    cycle_no INT NOT NULL,
    package_version INT NOT NULL,
    material_id VARCHAR(64) NOT NULL,
    quantity DECIMAL(18, 3) NOT NULL,
    unit VARCHAR(16) NOT NULL,
    CONSTRAINT uq_evidence_material UNIQUE (equipment_id, cycle_no, material_id)
);
COMMENT ON TABLE evidence_material_summary IS '证据包材料批次摘要：不可变；至少一个材料摘要是完工门禁之一';
COMMENT ON COLUMN evidence_material_summary.equipment_id IS '所属设备标识';
COMMENT ON COLUMN evidence_material_summary.cycle_no IS '所属保养周期号（同周期内批次不可重复，即使跨证据版本）';
COMMENT ON COLUMN evidence_material_summary.package_version IS '首次引用该批次的证据包版本号';
COMMENT ON COLUMN evidence_material_summary.material_id IS '材料批次号，引用时批次必须为 ACTIVE';
COMMENT ON COLUMN evidence_material_summary.quantity IS '实际用量，正数，精度到千分位，单位见 unit';
COMMENT ON COLUMN evidence_material_summary.unit IS '用量计量单位，提交时须与批次登记单位一致';

-- 双人完工确认：不可变；确认与保养落库、周期推进在同一事务原子完成。
CREATE TABLE IF NOT EXISTS maintenance_confirmation (
    confirmation_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
