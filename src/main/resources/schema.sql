-- 海洋盐度采样：航次、原始样本、冻结剖面、勘误。
-- H2 内存库 MODE=MySQL 下执行；时间列一律存 UTC 时刻。

CREATE TABLE IF NOT EXISTS voyage (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    voyage_code  VARCHAR(64)  NOT NULL,
    status       VARCHAR(16)  NOT NULL,
    sealed_utc   TIMESTAMP(3),
    created_utc  TIMESTAMP(3) NOT NULL,
    CONSTRAINT uk_voyage_code UNIQUE (voyage_code)
);
COMMENT ON TABLE voyage IS '航次：采样中为OPEN，封存后为SEALED；封存失败保持OPEN不锁定';
COMMENT ON COLUMN voyage.id IS '自增主键';
COMMENT ON COLUMN voyage.voyage_code IS '航次编号，业务唯一，非空';
COMMENT ON COLUMN voyage.status IS '航次状态：OPEN采样中，SEALED已封存剖面冻结';
COMMENT ON COLUMN voyage.sealed_utc IS '封存UTC时刻；未封存为NULL';
COMMENT ON COLUMN voyage.created_utc IS '航次创建UTC时刻，非空';

CREATE TABLE IF NOT EXISTS salinity_sample (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    voyage_code    VARCHAR(64)  NOT NULL,
    station_code   VARCHAR(64)  NOT NULL,
    depth_m        INT          NOT NULL,
    salinity_psu   DECIMAL(6,3) NOT NULL,
    collected_utc  TIMESTAMP(3) NOT NULL,
    sample_no      VARCHAR(64)  NOT NULL,
    request_id     VARCHAR(64),
    adopted        BOOLEAN      NOT NULL DEFAULT FALSE,
    superseded_by  BIGINT,
    created_utc    TIMESTAMP(3) NOT NULL,
    CONSTRAINT uk_sample_no UNIQUE (sample_no),
    CONSTRAINT uk_sample_request UNIQUE (request_id),
    CONSTRAINT fk_sample_voyage FOREIGN KEY (voyage_code) REFERENCES voyage (voyage_code),
    CONSTRAINT fk_sample_superseder FOREIGN KEY (superseded_by) REFERENCES salinity_sample (id)
);
COMMENT ON TABLE salinity_sample IS '盐度样本原始记录：每次重测各一行永久保留，不覆盖不删除';
COMMENT ON COLUMN salinity_sample.id IS '自增主键';
COMMENT ON COLUMN salinity_sample.voyage_code IS '所属航次编号，非空';
COMMENT ON COLUMN salinity_sample.station_code IS '站位编号，非空';
COMMENT ON COLUMN salinity_sample.depth_m IS '采样深度，单位米，允许0至500（含边界）';
COMMENT ON COLUMN salinity_sample.salinity_psu IS '盐度，单位PSU实用盐度标度，允许0至45（含边界）';
COMMENT ON COLUMN salinity_sample.collected_utc IS '样本采集UTC时刻，非空';
COMMENT ON COLUMN salinity_sample.sample_no IS '采样编号，全局唯一，非空';
COMMENT ON COLUMN salinity_sample.request_id IS '提交请求ID，用于幂等重放；未携带为NULL，非空时全局唯一';
COMMENT ON COLUMN salinity_sample.adopted IS '是否为站位深度当前采纳版本：TRUE是，FALSE否；每站位深度至多一条TRUE，由事务行锁保证';
COMMENT ON COLUMN salinity_sample.superseded_by IS '替换本样本的重测样本主键；未被替换为NULL';
COMMENT ON COLUMN salinity_sample.created_utc IS '样本入库UTC时刻，非空';

CREATE INDEX IF NOT EXISTS idx_sample_voyage ON salinity_sample (voyage_code);
CREATE INDEX IF NOT EXISTS idx_sample_position ON salinity_sample (voyage_code, station_code, depth_m);

CREATE TABLE IF NOT EXISTS sealed_profile_point (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    voyage_code    VARCHAR(64)  NOT NULL,
    station_code   VARCHAR(64)  NOT NULL,
    depth_m        INT          NOT NULL,
    sample_id      BIGINT       NOT NULL,
    salinity_psu   DECIMAL(6,3) NOT NULL,
    collected_utc  TIMESTAMP(3) NOT NULL,
    sealed_utc     TIMESTAMP(3) NOT NULL,
    CONSTRAINT uk_profile_point UNIQUE (voyage_code, station_code, depth_m),
    CONSTRAINT fk_profile_voyage FOREIGN KEY (voyage_code) REFERENCES voyage (voyage_code),
    CONSTRAINT fk_profile_sample FOREIGN KEY (sample_id) REFERENCES salinity_sample (id)
);
COMMENT ON TABLE sealed_profile_point IS '封存时刻固化的冻结剖面点，封存后不再变化';
COMMENT ON COLUMN sealed_profile_point.id IS '自增主键';
COMMENT ON COLUMN sealed_profile_point.voyage_code IS '航次编号，非空';
COMMENT ON COLUMN sealed_profile_point.station_code IS '站位编号，非空';
COMMENT ON COLUMN sealed_profile_point.depth_m IS '深度，单位米；固化标准层0、50、100';
COMMENT ON COLUMN sealed_profile_point.sample_id IS '被固化采纳样本的主键，非空';
COMMENT ON COLUMN sealed_profile_point.salinity_psu IS '固化时盐度快照，单位PSU';
COMMENT ON COLUMN sealed_profile_point.collected_utc IS '样本采集UTC时刻快照';
COMMENT ON COLUMN sealed_profile_point.sealed_utc IS '航次封存UTC时刻，非空';

CREATE TABLE IF NOT EXISTS profile_erratum (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    voyage_code    VARCHAR(64)  NOT NULL,
    note           VARCHAR(1000) NOT NULL,
    ref_sealed_utc TIMESTAMP(3) NOT NULL,
    created_utc    TIMESTAMP(3) NOT NULL,
    CONSTRAINT fk_erasures_voyage FOREIGN KEY (voyage_code) REFERENCES voyage (voyage_code)
);
COMMENT ON TABLE profile_erratum IS '封存后勘误：仅追加，原冻结剖面继续可查';
COMMENT ON COLUMN profile_erratum.id IS '自增主键';
COMMENT ON COLUMN profile_erratum.voyage_code IS '航次编号，非空，必须已封存';
COMMENT ON COLUMN profile_erratum.note IS '更正说明正文，非空';
COMMENT ON COLUMN profile_erratum.ref_sealed_utc IS '所引用原封存的UTC时刻，非空';
COMMENT ON COLUMN profile_erratum.created_utc IS '勘误追加UTC时刻，非空';
