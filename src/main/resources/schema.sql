-- 设备工时保养判定：H2（MODE=MySQL）自动建表脚本。
-- 所有时刻字段均为 UTC（TIMESTAMP WITH TIME ZONE），分钟数为非负整数。

-- 设备主表：每台设备一行，版本号用于写操作乐观并发控制。
CREATE TABLE IF NOT EXISTS equipment (
    equipment_id VARCHAR(64) NOT NULL PRIMARY KEY,
    maintenance_period_minutes BIGINT NOT NULL,
    version BIGINT NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);
COMMENT ON TABLE equipment IS '设备主表：每台设备一行';
COMMENT ON COLUMN equipment.equipment_id IS '设备唯一标识（客户端提供）';
COMMENT ON COLUMN equipment.maintenance_period_minutes IS '保养周期（分钟），正整数，登记后不可修改';
COMMENT ON COLUMN equipment.version IS '设备版本号，初始 1；新增读数/修订/完成保养均校验 expectedVersion 并加一';
COMMENT ON COLUMN equipment.created_at IS '登记时刻（UTC）';

-- 工时读数当前值表：reading_id 设备内唯一，同设备同一采样时刻仅一条。
CREATE TABLE IF NOT EXISTS reading (
    equipment_id VARCHAR(64) NOT NULL,
    reading_id VARCHAR(64) NOT NULL,
    sampled_at TIMESTAMP WITH TIME ZONE NOT NULL,
    cumulative_minutes BIGINT NOT NULL,
    revision_no INT NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    PRIMARY KEY (equipment_id, reading_id),
    CONSTRAINT uq_reading_sampled_at UNIQUE (equipment_id, sampled_at)
);
COMMENT ON TABLE reading IS '工时读数当前值：按采样时刻排序后累计分钟须单调不减';
COMMENT ON COLUMN reading.equipment_id IS '所属设备标识';
COMMENT ON COLUMN reading.reading_id IS '读数标识，设备内唯一';
COMMENT ON COLUMN reading.sampled_at IS 'UTC 采样时刻；同设备同一时刻仅允许一条读数';
COMMENT ON COLUMN reading.cumulative_minutes IS '当前累计工时（分钟），非负整数，随修订更新';
COMMENT ON COLUMN reading.revision_no IS '当前修订号，初始 1，每次修订加一';
COMMENT ON COLUMN reading.created_at IS '读数登记时刻（UTC）';
COMMENT ON COLUMN reading.updated_at IS '最近一次修订时刻（UTC）';

-- 读数修订历史：每次修订追加一行，保留全部历史值。
CREATE TABLE IF NOT EXISTS reading_revision (
    equipment_id VARCHAR(64) NOT NULL,
    reading_id VARCHAR(64) NOT NULL,
    revision_no INT NOT NULL,
    cumulative_minutes BIGINT NOT NULL,
    request_id VARCHAR(128) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    PRIMARY KEY (equipment_id, reading_id, revision_no)
);
COMMENT ON TABLE reading_revision IS '读数修订历史：revision_no=1 为初始登记值，其后每行对应一次修订';
COMMENT ON COLUMN reading_revision.equipment_id IS '所属设备标识';
COMMENT ON COLUMN reading_revision.reading_id IS '读数标识';
COMMENT ON COLUMN reading_revision.revision_no IS '修订号，从 1 开始递增';
COMMENT ON COLUMN reading_revision.cumulative_minutes IS '该修订版本的累计工时（分钟）';
COMMENT ON COLUMN reading_revision.request_id IS '产生该修订的请求 requestId';
COMMENT ON COLUMN reading_revision.created_at IS '该修订生效时刻（UTC）';

-- 保养记录：锚定某读数的特定修订号，保存锚点时刻与工时快照，不允许删除。
CREATE TABLE IF NOT EXISTS maintenance (
    maintenance_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    equipment_id VARCHAR(64) NOT NULL,
    cycle_no INT NOT NULL,
    reading_id VARCHAR(64) NOT NULL,
    anchor_revision_no INT NOT NULL,
    template_version INT NOT NULL,
    package_version INT NOT NULL,
    anchor_sampled_at TIMESTAMP WITH TIME ZONE NOT NULL,
    anchor_cumulative_minutes BIGINT NOT NULL,
    request_id VARCHAR(128) NOT NULL,
    completed_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_maintenance_equipment ON maintenance (equipment_id, anchor_sampled_at);
COMMENT ON TABLE maintenance IS '保养记录：锚点时间须严格晚于上次保养锚点；作为锚点的读数不可再修订';
COMMENT ON COLUMN maintenance.maintenance_id IS '保养记录自增主键';
COMMENT ON COLUMN maintenance.equipment_id IS '所属设备标识';
COMMENT ON COLUMN maintenance.cycle_no IS '完成的保养周期序号，从 1 开始递增';
COMMENT ON COLUMN maintenance.reading_id IS '锚点读数标识';
COMMENT ON COLUMN maintenance.anchor_revision_no IS '锚点读数在保养完成时的修订号';
COMMENT ON COLUMN maintenance.template_version IS '完工时固化的保养模板版本';
COMMENT ON COLUMN maintenance.package_version IS '完工确认的证据包版本';
COMMENT ON COLUMN maintenance.anchor_sampled_at IS '锚点读数的 UTC 采样时刻（快照）';
COMMENT ON COLUMN maintenance.anchor_cumulative_minutes IS '锚点读数在保养完成时的累计工时快照（分钟）';
COMMENT ON COLUMN maintenance.request_id IS '完成保养请求的 requestId';
COMMENT ON COLUMN maintenance.completed_at IS '保养完成登记时刻（UTC）';

-- 保养模板（设备内版本化）：每个版本不可变；证据包首次提交时固化模板版本，后续模板修订不影响在途/历史周期。
CREATE TABLE IF NOT EXISTS maintenance_template (
    equipment_id VARCHAR(64) NOT NULL,
    template_version INT NOT NULL,
    overdue_threshold_minutes BIGINT NOT NULL,
    request_id VARCHAR(128) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    PRIMARY KEY (equipment_id, template_version)
);
COMMENT ON TABLE maintenance_template IS '保养模板：设备内递增版本，每个版本不可变';
COMMENT ON COLUMN maintenance_template.equipment_id IS '所属设备标识';
COMMENT ON COLUMN maintenance_template.template_version IS '模板版本号，从 1 开始递增；证据包固化提交时的版本';
COMMENT ON COLUMN maintenance_template.overdue_threshold_minutes IS 'OVERDUE 阈值（分钟）；本轮运行分钟左闭右开区间 [周期, 阈值) 为 DUE，达到阈值为 OVERDUE';
COMMENT ON COLUMN maintenance_template.request_id IS '创建/修订该模板版本的请求 requestId';
COMMENT ON COLUMN maintenance_template.created_at IS '模板版本创建时刻（UTC）';

-- 模板必检项：模板版本内按 ordinal 规范排序，item_code 在版本内唯一；行不可变。
CREATE TABLE IF NOT EXISTS maintenance_template_item (
    equipment_id VARCHAR(64) NOT NULL,
    template_version INT NOT NULL,
    ordinal INT NOT NULL,
    item_code VARCHAR(64) NOT NULL,
    item_title VARCHAR(200) NOT NULL,
    PRIMARY KEY (equipment_id, template_version, ordinal),
    CONSTRAINT uq_template_item_code UNIQUE (equipment_id, template_version, item_code)
);
COMMENT ON TABLE maintenance_template_item IS '模板必检项：按 ordinal 升序为规范排序，随模板版本固化不可变';
COMMENT ON COLUMN maintenance_template_item.equipment_id IS '所属设备标识';
COMMENT ON COLUMN maintenance_template_item.template_version IS '所属模板版本号';
COMMENT ON COLUMN maintenance_template_item.ordinal IS '模板内规范序号，从 0 开始，连续且不可变';
COMMENT ON COLUMN maintenance_template_item.item_code IS '检查项编码，模板版本内唯一';
COMMENT ON COLUMN maintenance_template_item.item_title IS '检查项名称（非空）';

-- 材料批次台账：全局共享，ACTIVE 可被证据引用；撤销后状态 REVOKED，台账行保留不删。
CREATE TABLE IF NOT EXISTS material (
    batch_code VARCHAR(32) NOT NULL PRIMARY KEY,
    status VARCHAR(16) NOT NULL,
    description VARCHAR(256),
    revoke_reason VARCHAR(256),
    request_id VARCHAR(128) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    revoked_at TIMESTAMP WITH TIME ZONE
);
COMMENT ON TABLE material IS '材料批次台账：ACTIVE 可引用，REVOKED 为已撤销；撤销不可恢复';
COMMENT ON COLUMN material.batch_code IS '材料批次编码，全局唯一，格式 MAT- 开头加 4-16 位大写字母数字';
COMMENT ON COLUMN material.status IS '材料状态：ACTIVE=在用，REVOKED=已撤销';
COMMENT ON COLUMN material.description IS '材料描述（可空，null 表示登记时未提供描述）';
COMMENT ON COLUMN material.revoke_reason IS '撤销原因（可空，null 表示尚未撤销或未填写原因）';
COMMENT ON COLUMN material.request_id IS '登记该材料的请求 requestId';
COMMENT ON COLUMN material.created_at IS '材料登记时刻（UTC）';
COMMENT ON COLUMN material.revoked_at IS '撤销时刻（UTC，未撤销时为 null）';

-- 证据包：设备每个保养周期内版本递增；周期号 = 已完成保养次数 + 1，行不可变。
CREATE TABLE IF NOT EXISTS evidence_package (
    equipment_id VARCHAR(64) NOT NULL,
    cycle_no INT NOT NULL,
    package_version INT NOT NULL,
    template_version INT NOT NULL,
    submitted_by VARCHAR(64) NOT NULL,
    request_id VARCHAR(128) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    PRIMARY KEY (equipment_id, cycle_no, package_version)
);
COMMENT ON TABLE evidence_package IS '保养证据包：设备周期内版本从 1 递增，每行不可变，不随模板修订改写';
COMMENT ON COLUMN evidence_package.equipment_id IS '所属设备标识';
COMMENT ON COLUMN evidence_package.cycle_no IS '保养周期序号，从 1 开始，完成保养后进入下一周期';
COMMENT ON COLUMN evidence_package.package_version IS '周期内证据包版本号，从 1 开始递增';
COMMENT ON COLUMN evidence_package.template_version IS '该证据包固化的模板版本（首次提交时确定）';
COMMENT ON COLUMN evidence_package.submitted_by IS '该版本提交人（维护人员标识），不可兼任完工确认人';
COMMENT ON COLUMN evidence_package.request_id IS '产生该证据包版本的请求 requestId';
COMMENT ON COLUMN evidence_package.created_at IS '证据包版本生成时刻（UTC，精度到纳秒，不截断）';

-- 检查项结果：证据包版本内每项一行快照，历史版本行保留不可变。
CREATE TABLE IF NOT EXISTS evidence_check_result (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    equipment_id VARCHAR(64) NOT NULL,
    cycle_no INT NOT NULL,
    package_version INT NOT NULL,
    ordinal INT NOT NULL,
    item_code VARCHAR(64) NOT NULL,
    result VARCHAR(8) NOT NULL,
    remark VARCHAR(256),
    submitted_by VARCHAR(64) NOT NULL,
    request_id VARCHAR(128) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_evidence_result_item UNIQUE (equipment_id, cycle_no, package_version, item_code)
);
CREATE INDEX IF NOT EXISTS idx_evidence_result ON evidence_check_result (equipment_id, cycle_no, package_version, ordinal);
COMMENT ON TABLE evidence_check_result IS '证据包检查项结果快照：PASS/FAIL，历史版本行不可变、不覆盖';
COMMENT ON COLUMN evidence_check_result.id IS '自增主键';
COMMENT ON COLUMN evidence_check_result.equipment_id IS '所属设备标识';
COMMENT ON COLUMN evidence_check_result.cycle_no IS '所属保养周期序号';
COMMENT ON COLUMN evidence_check_result.package_version IS '所属证据包版本';
COMMENT ON COLUMN evidence_check_result.ordinal IS '模板内规范序号，返回时按其升序排列';
COMMENT ON COLUMN evidence_check_result.item_code IS '检查项编码，须属于固化模板版本';
COMMENT ON COLUMN evidence_check_result.result IS '检查结果：PASS 或 FAIL';
COMMENT ON COLUMN evidence_check_result.remark IS '备注（可空，null 表示无备注）';
COMMENT ON COLUMN evidence_check_result.submitted_by IS '该结果提交人';
COMMENT ON COLUMN evidence_check_result.request_id IS '提交该结果的请求 requestId';
COMMENT ON COLUMN evidence_check_result.created_at IS '结果提交时刻（UTC）';

-- 材料批次摘要：同一设备同一周期对同一批次仅允许一条；随首次出现的证据包版本固化。
CREATE TABLE IF NOT EXISTS evidence_material (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    equipment_id VARCHAR(64) NOT NULL,
    cycle_no INT NOT NULL,
    batch_code VARCHAR(32) NOT NULL,
    added_version INT NOT NULL,
    quantity BIGINT NOT NULL,
    unit VARCHAR(16) NOT NULL,
    submitted_by VARCHAR(64) NOT NULL,
    request_id VARCHAR(128) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_evidence_material_batch UNIQUE (equipment_id, cycle_no, batch_code)
);
COMMENT ON TABLE evidence_material IS '证据包材料批次摘要：周期内批次不可重复，行不可变；版本 V 快照含 added_version<=V 的全部摘要';
COMMENT ON COLUMN evidence_material.id IS '自增主键';
COMMENT ON COLUMN evidence_material.equipment_id IS '所属设备标识';
COMMENT ON COLUMN evidence_material.cycle_no IS '所属保养周期序号';
COMMENT ON COLUMN evidence_material.batch_code IS '材料批次编码，须存在于台账且同一设备周期内不重复';
COMMENT ON COLUMN evidence_material.added_version IS '该摘要首次进入证据包时的证据包版本号';
COMMENT ON COLUMN evidence_material.quantity IS '使用数量（正整数，单位见 unit）';
COMMENT ON COLUMN evidence_material.unit IS '数量单位（非空，如 PCS）';
COMMENT ON COLUMN evidence_material.submitted_by IS '该摘要提交人';
COMMENT ON COLUMN evidence_material.request_id IS '提交该摘要的请求 requestId';
COMMENT ON COLUMN evidence_material.created_at IS '摘要提交时刻（UTC）';

-- 双人完工确认：与保养记录 1:1，原子插入；固化周期、模板版本、证据包版本与双方操作人，不可变。
CREATE TABLE IF NOT EXISTS maintenance_confirmation (
    maintenance_id BIGINT NOT NULL PRIMARY KEY,
    equipment_id VARCHAR(64) NOT NULL,
    cycle_no INT NOT NULL,
    template_version INT NOT NULL,
    package_version INT NOT NULL,
    submitter_id VARCHAR(64) NOT NULL,
    confirmer_id VARCHAR(64) NOT NULL,
    request_id VARCHAR(128) NOT NULL,
    confirmed_at TIMESTAMP WITH TIME ZONE NOT NULL
);
COMMENT ON TABLE maintenance_confirmation IS '双人完工确认：确认人与证据提交人必须不同，与保养完成同事务原子提交';
COMMENT ON COLUMN maintenance_confirmation.maintenance_id IS '对应保养记录主键（1:1）';
COMMENT ON COLUMN maintenance_confirmation.equipment_id IS '所属设备标识';
COMMENT ON COLUMN maintenance_confirmation.cycle_no IS '被确认的保养周期序号';
COMMENT ON COLUMN maintenance_confirmation.template_version IS '确认时固化的模板版本（与证据包一致）';
COMMENT ON COLUMN maintenance_confirmation.package_version IS '被确认的证据包版本（须为该周期最新版本）';
COMMENT ON COLUMN maintenance_confirmation.submitter_id IS '证据包提交人（不可确认自己提交的证据）';
COMMENT ON COLUMN maintenance_confirmation.confirmer_id IS '完工确认人（另一维护人员，不得为提交人）';
COMMENT ON COLUMN maintenance_confirmation.request_id IS '完工确认（完成保养）请求的 requestId';
COMMENT ON COLUMN maintenance_confirmation.confirmed_at IS '确认与完工时刻（UTC）';

-- 更正附录：完工后发现错误只能追加附录，不能重开周期或覆盖工时/证据历史。
CREATE TABLE IF NOT EXISTS evidence_appendix (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    equipment_id VARCHAR(64) NOT NULL,
    cycle_no INT NOT NULL,
    operator_id VARCHAR(64) NOT NULL,
    note VARCHAR(500) NOT NULL,
    request_id VARCHAR(128) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_evidence_appendix ON evidence_appendix (equipment_id, cycle_no, id);
COMMENT ON TABLE evidence_appendix IS '完工后更正附录：只追加，不可修改删除；不改变周期与工时历史';
COMMENT ON COLUMN evidence_appendix.id IS '自增主键';
COMMENT ON COLUMN evidence_appendix.equipment_id IS '所属设备标识';
COMMENT ON COLUMN evidence_appendix.cycle_no IS '关联的已完成保养周期序号';
COMMENT ON COLUMN evidence_appendix.operator_id IS '创建附录的操作人员';
COMMENT ON COLUMN evidence_appendix.note IS '更正说明（非空）';
COMMENT ON COLUMN evidence_appendix.request_id IS '创建附录请求的 requestId';
COMMENT ON COLUMN evidence_appendix.created_at IS '附录创建时刻（UTC）';

-- 幂等去重表：requestId 全局唯一；仅成功结果占键，失败回滚不占键。
CREATE TABLE IF NOT EXISTS idempotency_request (
    request_id VARCHAR(128) NOT NULL PRIMARY KEY,
    operation VARCHAR(48) NOT NULL,
    request_fingerprint VARCHAR(512) NOT NULL,
    response_body CLOB NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);
COMMENT ON TABLE idempotency_request IS '写操作幂等去重：同键同参重放原成功结果，同键异参返回 409';
COMMENT ON COLUMN idempotency_request.request_id IS '全局唯一请求标识';
COMMENT ON COLUMN idempotency_request.operation IS '操作类型（登记设备/新增读数/修订/完成保养）';
COMMENT ON COLUMN idempotency_request.request_fingerprint IS '业务参数指纹（不含 requestId），用于同键异参判定';
COMMENT ON COLUMN idempotency_request.response_body IS '原成功响应报文（JSON），重放时原样返回';
COMMENT ON COLUMN idempotency_request.created_at IS '首次成功处理时刻（UTC）';
