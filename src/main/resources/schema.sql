-- 设备工时保养判定 + 能源隔离：H2（MODE=MySQL）自动建表脚本。
-- 所有时刻字段均为 UTC（TIMESTAMP WITH TIME ZONE），分钟数为非负整数。
-- 时间区间一律左闭右开；历史表只追加，不更新、不删除（锁定点状态列除外，其变更由事件表留痕）。

-- 设备主表：每台设备一行，版本号用于写操作乐观并发控制。
CREATE TABLE IF NOT EXISTS equipment (
    equipment_id VARCHAR(64) NOT NULL PRIMARY KEY,
    maintenance_period_minutes BIGINT NOT NULL,
    version BIGINT NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    status VARCHAR(16) NOT NULL DEFAULT 'ACTIVE',
    deactivated_at TIMESTAMP WITH TIME ZONE NULL
);
COMMENT ON TABLE equipment IS '设备主表：每台设备一行；status=ACTIVE 可作业，DEACTIVATED 已停用';
COMMENT ON COLUMN equipment.equipment_id IS '设备唯一标识（客户端提供）';
COMMENT ON COLUMN equipment.maintenance_period_minutes IS '保养周期（分钟），正整数，登记后不可修改';
COMMENT ON COLUMN equipment.version IS '设备版本号，初始 1；新增读数/修订/完成保养/创建隔离/解除隔离/停用均校验 expectedVersion 并加一（锁定点确认除外）';
COMMENT ON COLUMN equipment.created_at IS '登记时刻（UTC）';
COMMENT ON COLUMN equipment.status IS '设备状态：ACTIVE 在用 / DEACTIVATED 已停用；停用后不可再创建隔离或提交读数、保养';
COMMENT ON COLUMN equipment.deactivated_at IS '停用时刻（UTC）；ACTIVE 设备为 null';

-- 工时读数当前值表：reading_id 设备内唯一，同设备同一采样时刻仅一条。
CREATE TABLE IF NOT EXISTS reading (
    equipment_id VARCHAR(64) NOT NULL,
    reading_id VARCHAR(64) NOT NULL,
    sampled_at TIMESTAMP WITH TIME ZONE NOT NULL,
    cumulative_minutes BIGINT NOT NULL,
    revision_no INT NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    PRIMARY KEY (equipment_id, reading_id),
    CONSTRAINT uq_reading_sampled_at UNIQUE (equipment_id, sampled_at)
);
COMMENT ON TABLE reading IS '工时读数当前值：按采样时刻排序后累计分钟须单调不减';
COMMENT ON COLUMN reading.equipment_id IS '所属设备标识';
COMMENT ON COLUMN reading.reading_id IS '读数标识，设备内唯一';
COMMENT ON COLUMN reading.sampled_at IS 'UTC 采样时刻；同设备同一时刻仅允许一条读数';
COMMENT ON COLUMN reading.cumulative_minutes IS '当前累计工时（分钟），非负整数，随修订更新';
COMMENT ON COLUMN reading.revision_no IS '当前修订号，初始 1，每次修订加一';
COMMENT ON COLUMN reading.created_at IS '读数登记时刻（UTC）';
COMMENT ON COLUMN reading.updated_at IS '最近一次修订时刻（UTC）';

-- 读数修订历史：每次修订追加一行，保留全部历史值。
CREATE TABLE IF NOT EXISTS reading_revision (
    equipment_id VARCHAR(64) NOT NULL,
    reading_id VARCHAR(64) NOT NULL,
    revision_no INT NOT NULL,
    cumulative_minutes BIGINT NOT NULL,
    request_id VARCHAR(128) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    PRIMARY KEY (equipment_id, reading_id, revision_no)
);
COMMENT ON TABLE reading_revision IS '读数修订历史：revision_no=1 为初始登记值，其后每行对应一次修订';
COMMENT ON COLUMN reading_revision.equipment_id IS '所属设备标识';
COMMENT ON COLUMN reading_revision.reading_id IS '读数标识';
COMMENT ON COLUMN reading_revision.revision_no IS '修订号，从 1 开始递增';
COMMENT ON COLUMN reading_revision.cumulative_minutes IS '该修订版本的累计工时（分钟）';
COMMENT ON COLUMN reading_revision.request_id IS '产生该修订的请求 requestId';
COMMENT ON COLUMN reading_revision.created_at IS '该修订生效时刻（UTC）';

-- 保养记录：锚定某读数的特定修订号，保存锚点时刻与工时快照，不允许删除。
CREATE TABLE IF NOT EXISTS maintenance (
    maintenance_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    equipment_id VARCHAR(64) NOT NULL,
    reading_id VARCHAR(64) NOT NULL,
    anchor_revision_no INT NOT NULL,
    anchor_sampled_at TIMESTAMP WITH TIME ZONE NOT NULL,
    anchor_cumulative_minutes BIGINT NOT NULL,
    request_id VARCHAR(128) NOT NULL,
    completed_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_maintenance_equipment ON maintenance (equipment_id, anchor_sampled_at);
COMMENT ON TABLE maintenance IS '保养记录：锚点时间须严格晚于上次保养锚点；作为锚点的读数不可再修订；能源隔离期间仍可提交';
COMMENT ON COLUMN maintenance.maintenance_id IS '保养记录自增主键';
COMMENT ON COLUMN maintenance.equipment_id IS '所属设备标识';
COMMENT ON COLUMN maintenance.reading_id IS '锚点读数标识';
COMMENT ON COLUMN maintenance.anchor_revision_no IS '锚点读数在保养完成时的修订号';
COMMENT ON COLUMN maintenance.anchor_sampled_at IS '锚点读数的 UTC 采样时刻（快照）';
COMMENT ON COLUMN maintenance.anchor_cumulative_minutes IS '锚点读数在保养完成时的累计工时快照（分钟）';
COMMENT ON COLUMN maintenance.request_id IS '完成保养请求的 requestId';
COMMENT ON COLUMN maintenance.completed_at IS '保养完成登记时刻（UTC）';

-- 能源隔离令：每台设备同时至多一条非 RELEASED 隔离令（由服务层设备行锁串行化保证）。
CREATE TABLE IF NOT EXISTS energy_isolation_order (
    order_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    equipment_id VARCHAR(64) NOT NULL,
    status VARCHAR(16) NOT NULL,
    created_by VARCHAR(64) NOT NULL,
    created_request_id VARCHAR(128) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    effective_at TIMESTAMP WITH TIME ZONE NULL,
    released_at TIMESTAMP WITH TIME ZONE NULL,
    released_by VARCHAR(64) NULL,
    released_request_id VARCHAR(128) NULL,
    release_reason VARCHAR(512) NULL
);
CREATE INDEX IF NOT EXISTS idx_isolation_equipment_status
    ON energy_isolation_order (equipment_id, status);
COMMENT ON TABLE energy_isolation_order IS '能源隔离令：PENDING 待双角色确认全部锁定点，EFFECTIVE 已生效（拒绝新增读数），RELEASED 已全部解除';
COMMENT ON COLUMN energy_isolation_order.order_id IS '隔离令自增主键';
COMMENT ON COLUMN energy_isolation_order.equipment_id IS '所属设备标识';
COMMENT ON COLUMN energy_isolation_order.status IS '令状态：PENDING / EFFECTIVE / RELEASED';
COMMENT ON COLUMN energy_isolation_order.created_by IS '创建操作人';
COMMENT ON COLUMN energy_isolation_order.created_request_id IS '创建隔离令请求的 requestId（批量创建时为批量 requestId）';
COMMENT ON COLUMN energy_isolation_order.created_at IS '隔离令创建时刻（UTC）';
COMMENT ON COLUMN energy_isolation_order.effective_at IS '全部锁定点双角色确认完成、隔离生效时刻（UTC）；未生效为 null';
COMMENT ON COLUMN energy_isolation_order.released_at IS '全部锁定点逐一解除、令解除时刻（UTC）；未解除为 null';
COMMENT ON COLUMN energy_isolation_order.released_by IS '解除操作人；未解除为 null';
COMMENT ON COLUMN energy_isolation_order.released_request_id IS '解除请求的 requestId；未解除为 null';
COMMENT ON COLUMN energy_isolation_order.release_reason IS '解除原因（必填），解除时写入；未解除为 null';

-- 隔离锁定点：每令一组，创建时固化；两个维护角色 ISOLATOR/VERIFIER 各确认一次后方可生效。
CREATE TABLE IF NOT EXISTS isolation_lock_point (
    order_id BIGINT NOT NULL,
    ordinal INT NOT NULL,
    lock_point_id VARCHAR(64) NOT NULL,
    description VARCHAR(256) NOT NULL,
    confirmed_isolator_by VARCHAR(64) NULL,
    confirmed_isolator_request_id VARCHAR(128) NULL,
    confirmed_isolator_at TIMESTAMP WITH TIME ZONE NULL,
    confirmed_verifier_by VARCHAR(64) NULL,
    confirmed_verifier_request_id VARCHAR(128) NULL,
    confirmed_verifier_at TIMESTAMP WITH TIME ZONE NULL,
    released_by VARCHAR(64) NULL,
    released_request_id VARCHAR(128) NULL,
    released_at TIMESTAMP WITH TIME ZONE NULL,
    PRIMARY KEY (order_id, lock_point_id)
);
COMMENT ON TABLE isolation_lock_point IS '隔离锁定点：同一令内 lock_point_id 唯一；ordinal 为提交序号，查询稳定排序';
COMMENT ON COLUMN isolation_lock_point.order_id IS '所属隔离令标识';
COMMENT ON COLUMN isolation_lock_point.ordinal IS '锁定点在创建请求中的提交序号（从 0 开始）';
COMMENT ON COLUMN isolation_lock_point.lock_point_id IS '锁定点标识，令内唯一，重复提交返回 422';
COMMENT ON COLUMN isolation_lock_point.description IS '锁定点描述（如能源类型与物理位置）';
COMMENT ON COLUMN isolation_lock_point.confirmed_isolator_by IS 'ISOLATOR 角色确认操作人；未确认 null';
COMMENT ON COLUMN isolation_lock_point.confirmed_isolator_request_id IS 'ISOLATOR 确认请求 requestId；未确认 null';
COMMENT ON COLUMN isolation_lock_point.confirmed_isolator_at IS 'ISOLATOR 确认时刻（UTC）；未确认 null';
COMMENT ON COLUMN isolation_lock_point.confirmed_verifier_by IS 'VERIFIER 角色确认操作人；未确认 null';
COMMENT ON COLUMN isolation_lock_point.confirmed_verifier_request_id IS 'VERIFIER 确认请求 requestId；未确认 null';
COMMENT ON COLUMN isolation_lock_point.confirmed_verifier_at IS 'VERIFIER 确认时刻（UTC）；未确认 null';
COMMENT ON COLUMN isolation_lock_point.released_by IS '该点解除操作人；未解除 null';
COMMENT ON COLUMN isolation_lock_point.released_request_id IS '该点解除请求 requestId；未解除 null';
COMMENT ON COLUMN isolation_lock_point.released_at IS '该点解除时刻（UTC）；未解除 null';

-- 隔离事件流：只追加，固化锁定点、角色与操作人；order_id 可空以承载设备级事件（停用）。
CREATE TABLE IF NOT EXISTS isolation_event (
    event_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NULL,
    equipment_id VARCHAR(64) NOT NULL,
    event_type VARCHAR(32) NOT NULL,
    lock_point_id VARCHAR(64) NULL,
    lock_role VARCHAR(16) NULL,
    operator_id VARCHAR(64) NULL,
    request_id VARCHAR(128) NULL,
    detail VARCHAR(512) NULL,
    event_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_isolation_event_order ON isolation_event (order_id, event_id);
CREATE INDEX IF NOT EXISTS idx_isolation_event_equipment_time
    ON isolation_event (equipment_id, event_at);
COMMENT ON TABLE isolation_event IS '隔离审计事件流（只追加）：CREATED/CONFIRMED/EFFECTIVE/RELEASE_POINT/RELEASED/DEACTIVATED';
COMMENT ON COLUMN isolation_event.event_id IS '事件自增主键，同时为稳定排序键';
COMMENT ON COLUMN isolation_event.order_id IS '关联隔离令标识；设备级事件（DEACTIVATED）为 null';
COMMENT ON COLUMN isolation_event.equipment_id IS '所属设备标识';
COMMENT ON COLUMN isolation_event.event_type IS '事件类型';
COMMENT ON COLUMN isolation_event.lock_point_id IS '事件关联锁定点标识；令级/设备级事件为 null';
COMMENT ON COLUMN isolation_event.lock_role IS '确认事件的维护角色：ISOLATOR/VERIFIER；其余事件 null';
COMMENT ON COLUMN isolation_event.operator_id IS '事件操作人';
COMMENT ON COLUMN isolation_event.request_id IS '产生该事件的请求 requestId';
COMMENT ON COLUMN isolation_event.detail IS '事件补充说明（如解除原因），无补充为 null';
COMMENT ON COLUMN isolation_event.event_at IS '事件发生时刻（UTC）';

-- 被拒读数证据：隔离令解除前提交的新增读数被 409 拒绝时，以独立事务固化，主业务事务回滚不影响本证据。
CREATE TABLE IF NOT EXISTS rejected_reading (
    rejected_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    equipment_id VARCHAR(64) NOT NULL,
    order_id BIGINT NOT NULL,
    request_id VARCHAR(128) NOT NULL,
    operator_id VARCHAR(64) NULL,
    reading_id VARCHAR(64) NOT NULL,
    sampled_at TIMESTAMP WITH TIME ZONE NOT NULL,
    cumulative_minutes BIGINT NOT NULL,
    expected_version BIGINT NOT NULL,
    lock_point_ids VARCHAR(512) NOT NULL,
    reason_code VARCHAR(48) NOT NULL,
    rejected_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_rejected_reading_equipment_time
    ON rejected_reading (equipment_id, rejected_at);
COMMENT ON TABLE rejected_reading IS '被隔离拒绝的新增运行读数证据（只追加）：拒绝返回 409，读数本身不写入、版本不前进、幂等键不占用';
COMMENT ON COLUMN rejected_reading.rejected_id IS '拒绝记录自增主键，同时为稳定排序键';
COMMENT ON COLUMN rejected_reading.equipment_id IS '被拒读数所属设备标识';
COMMENT ON COLUMN rejected_reading.order_id IS '当时生效（或待生效）的隔离令标识';
COMMENT ON COLUMN rejected_reading.request_id IS '被拒读数请求的 requestId（失败不占幂等键，可在解除后复用）';
COMMENT ON COLUMN rejected_reading.operator_id IS '提交读数的操作人；请求未提供时为 null';
COMMENT ON COLUMN rejected_reading.reading_id IS '被拒读数标识（未落入 reading 表）';
COMMENT ON COLUMN rejected_reading.sampled_at IS '被拒读数的 UTC 采样时刻';
COMMENT ON COLUMN rejected_reading.cumulative_minutes IS '被拒读数申报的累计工时（分钟）';
COMMENT ON COLUMN rejected_reading.expected_version IS '被拒请求携带的设备期望版本号';
COMMENT ON COLUMN rejected_reading.lock_point_ids IS '被拒时刻隔离令锁定点标识集合快照（按标识升序的规范化 JSON 数组）';
COMMENT ON COLUMN rejected_reading.reason_code IS '拒绝原因码，如 READING_REJECTED_UNDER_ISOLATION';
COMMENT ON COLUMN rejected_reading.rejected_at IS '拒绝时刻（UTC）';

-- 幂等去重表：requestId 全局唯一；仅成功结果占键，失败回滚不占键。
CREATE TABLE IF NOT EXISTS idempotency_request (
    request_id VARCHAR(128) NOT NULL PRIMARY KEY,
    operation VARCHAR(48) NOT NULL,
    request_fingerprint VARCHAR(512) NOT NULL,
    response_body CLOB NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);
COMMENT ON TABLE idempotency_request IS '写操作幂等去重：同键同参重放原成功结果，同键异参返回 409';
COMMENT ON COLUMN idempotency_request.request_id IS '全局唯一请求标识';
COMMENT ON COLUMN idempotency_request.operation IS '操作类型（登记设备/新增读数/修订/完成保养/隔离创建/批量隔离/确认/解除/停用）';
COMMENT ON COLUMN idempotency_request.request_fingerprint IS '业务参数指纹（SHA-256，规范化 JSON 含操作者/操作类型/规范化集合/全部结果字段），用于同键异参判定';
COMMENT ON COLUMN idempotency_request.response_body IS '原成功响应报文（JSON），重放时原样返回';
COMMENT ON COLUMN idempotency_request.created_at IS '首次成功处理时刻（UTC）';
