-- 设备工时保养判定：H2（MODE=MySQL）自动建表脚本。
-- 所有时刻字段均为 UTC（TIMESTAMP WITH TIME ZONE），分钟数为非负整数。

-- 设备主表：每台设备一行，版本号用于写操作乐观并发控制。
CREATE TABLE IF NOT EXISTS equipment (
    equipment_id VARCHAR(64) NOT NULL PRIMARY KEY,
    maintenance_period_minutes BIGINT NOT NULL,
    version BIGINT NOT NULL,
    status VARCHAR(16) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);
COMMENT ON TABLE equipment IS '设备主表：每台设备一行';
COMMENT ON COLUMN equipment.equipment_id IS '设备唯一标识（客户端提供）';
COMMENT ON COLUMN equipment.maintenance_period_minutes IS '保养周期（分钟），正整数，登记后不可修改';
COMMENT ON COLUMN equipment.version IS '设备版本号，初始 1；新增读数/修订/完成保养/停用均校验 expectedVersion 并加一；隔离令流转不改变版本';
COMMENT ON COLUMN equipment.status IS '设备状态：ACTIVE 在用 / DECOMMISSIONED 已停用；已停用设备不可创建能源隔离令';
COMMENT ON COLUMN equipment.created_at IS '登记时刻（UTC）';

-- 工时读数当前值表：reading_id 设备内唯一，同设备同一采样时刻仅一条。
CREATE TABLE IF NOT EXISTS reading (
    equipment_id VARCHAR(64) NOT NULL,
    reading_id VARCHAR(64) NOT NULL,
    sampled_at TIMESTAMP WITH TIME ZONE NOT NULL,
    cumulative_minutes BIGINT NOT NULL,
    revision_no INT NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    PRIMARY KEY (equipment_id, reading_id),
    CONSTRAINT uq_reading_sampled_at UNIQUE (equipment_id, sampled_at)
);
COMMENT ON TABLE reading IS '工时读数当前值：按采样时刻排序后累计分钟须单调不减';
COMMENT ON COLUMN reading.equipment_id IS '所属设备标识';
COMMENT ON COLUMN reading.reading_id IS '读数标识，设备内唯一';
COMMENT ON COLUMN reading.sampled_at IS 'UTC 采样时刻；同设备同一时刻仅允许一条读数';
COMMENT ON COLUMN reading.cumulative_minutes IS '当前累计工时（分钟），非负整数，随修订更新';
COMMENT ON COLUMN reading.revision_no IS '当前修订号，初始 1，每次修订加一';
COMMENT ON COLUMN reading.created_at IS '读数登记时刻（UTC）';
COMMENT ON COLUMN reading.updated_at IS '最近一次修订时刻（UTC）';

-- 读数修订历史：每次修订追加一行，保留全部历史值。
CREATE TABLE IF NOT EXISTS reading_revision (
    equipment_id VARCHAR(64) NOT NULL,
    reading_id VARCHAR(64) NOT NULL,
    revision_no INT NOT NULL,
    cumulative_minutes BIGINT NOT NULL,
    request_id VARCHAR(128) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    PRIMARY KEY (equipment_id, reading_id, revision_no)
);
COMMENT ON TABLE reading_revision IS '读数修订历史：revision_no=1 为初始登记值，其后每行对应一次修订';
COMMENT ON COLUMN reading_revision.equipment_id IS '所属设备标识';
COMMENT ON COLUMN reading_revision.reading_id IS '读数标识';
COMMENT ON COLUMN reading_revision.revision_no IS '修订号，从 1 开始递增';
COMMENT ON COLUMN reading_revision.cumulative_minutes IS '该修订版本的累计工时（分钟）';
COMMENT ON COLUMN reading_revision.request_id IS '产生该修订的请求 requestId';
COMMENT ON COLUMN reading_revision.created_at IS '该修订生效时刻（UTC）';

-- 保养记录：锚定某读数的特定修订号，保存锚点时刻与工时快照，不允许删除。
CREATE TABLE IF NOT EXISTS maintenance (
    maintenance_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    equipment_id VARCHAR(64) NOT NULL,
    reading_id VARCHAR(64) NOT NULL,
    anchor_revision_no INT NOT NULL,
    anchor_sampled_at TIMESTAMP WITH TIME ZONE NOT NULL,
    anchor_cumulative_minutes BIGINT NOT NULL,
    request_id VARCHAR(128) NOT NULL,
    completed_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_maintenance_equipment ON maintenance (equipment_id, anchor_sampled_at);
COMMENT ON TABLE maintenance IS '保养记录：锚点时间须严格晚于上次保养锚点；作为锚点的读数不可再修订';
COMMENT ON COLUMN maintenance.maintenance_id IS '保养记录自增主键';
COMMENT ON COLUMN maintenance.equipment_id IS '所属设备标识';
COMMENT ON COLUMN maintenance.reading_id IS '锚点读数标识';
COMMENT ON COLUMN maintenance.anchor_revision_no IS '锚点读数在保养完成时的修订号';
COMMENT ON COLUMN maintenance.anchor_sampled_at IS '锚点读数的 UTC 采样时刻（快照）';
COMMENT ON COLUMN maintenance.anchor_cumulative_minutes IS '锚点读数在保养完成时的累计工时快照（分钟）';
COMMENT ON COLUMN maintenance.request_id IS '完成保养请求的 requestId';
COMMENT ON COLUMN maintenance.completed_at IS '保养完成登记时刻（UTC）';

-- 幂等去重表：requestId 全局唯一；仅成功结果占键，失败回滚不占键。
CREATE TABLE IF NOT EXISTS idempotency_request (
    request_id VARCHAR(128) NOT NULL PRIMARY KEY,
    operation VARCHAR(48) NOT NULL,
    request_fingerprint VARCHAR(512) NOT NULL,
    response_body CLOB NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);
COMMENT ON TABLE idempotency_request IS '写操作幂等去重：同键同参重放原成功结果，同键异参返回 409';
COMMENT ON COLUMN idempotency_request.request_id IS '全局唯一请求标识';
COMMENT ON COLUMN idempotency_request.operation IS '操作类型（登记设备/新增读数/修订/完成保养）';
COMMENT ON COLUMN idempotency_request.request_fingerprint IS '业务参数指纹（不含 requestId），用于同键异参判定';
COMMENT ON COLUMN idempotency_request.response_body IS '原成功响应报文（JSON），重放时原样返回';
COMMENT ON COLUMN idempotency_request.created_at IS '首次成功处理时刻（UTC）';

-- 能源隔离令：对设备创建隔离令，要求两名不同维护角色分别确认所有锁定点后生效。
CREATE TABLE IF NOT EXISTS isolation_order (
    order_id VARCHAR(64) NOT NULL PRIMARY KEY,
    equipment_id VARCHAR(64) NOT NULL,
    state VARCHAR(16) NOT NULL,
    created_by VARCHAR(64) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    effective_at TIMESTAMP WITH TIME ZONE,
    released_at TIMESTAMP WITH TIME ZONE,
    released_by VARCHAR(64),
    release_reason VARCHAR(512)
);
CREATE INDEX IF NOT EXISTS idx_isolation_order_equipment ON isolation_order (equipment_id, created_at);
COMMENT ON TABLE isolation_order IS '能源隔离令：PENDING（待双角色确认）/ISOLATED（隔离生效）/RELEASED（已解除）；同设备同时至多一个未结束（PENDING/ISOLATED）隔离令';
COMMENT ON COLUMN isolation_order.order_id IS '隔离令唯一标识（客户端提供）';
COMMENT ON COLUMN isolation_order.equipment_id IS '所属设备标识';
COMMENT ON COLUMN isolation_order.state IS '隔离令状态：PENDING/ISOLATED/RELEASED';
COMMENT ON COLUMN isolation_order.created_by IS '创建隔离令的操作者（创建时固化）';
COMMENT ON COLUMN isolation_order.created_at IS '隔离令创建时刻（UTC）';
COMMENT ON COLUMN isolation_order.effective_at IS '隔离生效时刻（UTC）；PENDING 时为 null，生效后不可改写';
COMMENT ON COLUMN isolation_order.released_at IS '解除时刻（UTC）；未解除时为 null';
COMMENT ON COLUMN isolation_order.released_by IS '执行解除的操作者；未解除时为 null';
COMMENT ON COLUMN isolation_order.release_reason IS '解除原因；未解除时为 null';

-- 隔离锁定点：隔离令创建时一次性固化；确认状态由 lock_event 中两类角色事件推导，解除逐点记录。
CREATE TABLE IF NOT EXISTS lock_point (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id VARCHAR(64) NOT NULL,
    point_id VARCHAR(64) NOT NULL,
    seq_no INT NOT NULL,
    released_at TIMESTAMP WITH TIME ZONE,
    released_by VARCHAR(64),
    release_reason VARCHAR(512),
    UNIQUE (order_id, point_id),
    CONSTRAINT uq_lock_point_seq UNIQUE (order_id, seq_no)
);
COMMENT ON TABLE lock_point IS '隔离锁定点快照：创建时固化 point_id 与顺序；两个角色的确认状态见 lock_event，禁止删除改写';
COMMENT ON COLUMN lock_point.id IS '锁定点自增主键';
COMMENT ON COLUMN lock_point.order_id IS '所属隔离令标识';
COMMENT ON COLUMN lock_point.point_id IS '锁定点业务标识，隔离令内唯一，创建后固化';
COMMENT ON COLUMN lock_point.seq_no IS '锁定点在隔离令内的规范化顺序（从 1 开始），用于稳定排序';
COMMENT ON COLUMN lock_point.released_at IS '该点解除时刻（UTC）；未解除为 null';
COMMENT ON COLUMN lock_point.released_by IS '解除该点的操作人；未解除为 null';
COMMENT ON COLUMN lock_point.release_reason IS '该点解除原因（非空）；未解除为 null';

-- 锁定点事件流水：每次确认/解除追加一行，作为不可改写的业务证据。
CREATE TABLE IF NOT EXISTS lock_event (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id VARCHAR(64) NOT NULL,
    seq_no INT NOT NULL,
    point_id VARCHAR(64) NOT NULL,
    event_type VARCHAR(16) NOT NULL,
    role VARCHAR(32),
    operator VARCHAR(64) NOT NULL,
    request_id VARCHAR(128) NOT NULL,
    reason VARCHAR(512),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_lock_event_order ON lock_event (order_id, id);
COMMENT ON TABLE lock_event IS '锁定点确认/解除事件流水：只追加，固化锁定点快照与操作人，禁止更新删除';
COMMENT ON COLUMN lock_event.order_id IS '所属隔离令标识';
COMMENT ON COLUMN lock_event.seq_no IS '事件发生时锁定点的规范化顺序快照';
COMMENT ON COLUMN lock_event.point_id IS '事件发生时锁定点标识快照';
COMMENT ON COLUMN lock_event.event_type IS '事件类型：CONFIRM 确认 / RELEASE 解除';
COMMENT ON COLUMN lock_event.role IS '确认角色（ELECTRICIAN/MECHANIC）；解除事件为 null';
COMMENT ON COLUMN lock_event.operator IS '执行操作的操作者';
COMMENT ON COLUMN lock_event.request_id IS '产生该事件的请求 requestId';
COMMENT ON COLUMN lock_event.reason IS '解除原因；确认事件为 null';
COMMENT ON COLUMN lock_event.created_at IS '事件发生时刻（UTC）';

-- 隔离生效期间被拒绝的新增读数：固化证据，用于诊断查询，禁止更新删除。
CREATE TABLE IF NOT EXISTS rejected_reading (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    equipment_id VARCHAR(64) NOT NULL,
    order_id VARCHAR(64) NOT NULL,
    reading_id VARCHAR(64) NOT NULL,
    sampled_at TIMESTAMP WITH TIME ZONE NOT NULL,
    cumulative_minutes BIGINT NOT NULL,
    requested_by VARCHAR(64),
    request_id VARCHAR(128) NOT NULL,
    rejected_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_rejected_reading_equipment ON rejected_reading (equipment_id, id);
COMMENT ON TABLE rejected_reading IS '隔离生效期间被拒新增读数证据：返回 409 的同时固化；保养提交不受隔离限制';
COMMENT ON COLUMN rejected_reading.equipment_id IS '被拒读数所属设备标识';
COMMENT ON COLUMN rejected_reading.order_id IS '当时生效的隔离令标识';
COMMENT ON COLUMN rejected_reading.reading_id IS '被拒读数标识';
COMMENT ON COLUMN rejected_reading.sampled_at IS '被拒读数的 UTC 采样时刻';
COMMENT ON COLUMN rejected_reading.cumulative_minutes IS '被拒读数申报的累计工时（分钟）';
COMMENT ON COLUMN rejected_reading.requested_by IS '提交读数的操作者；请求未提供操作者时为 null';
COMMENT ON COLUMN rejected_reading.request_id IS '被拒请求的 requestId';
COMMENT ON COLUMN rejected_reading.rejected_at IS '拒绝发生时刻（UTC）';
