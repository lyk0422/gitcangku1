-- 设备工时保养判定 + 保养证据包：H2（MODE=MySQL）自动建表脚本。
-- 所有时刻字段均为 UTC（TIMESTAMP WITH TIME ZONE），分钟数为非负整数。

-- 设备主表：每台设备一行，版本号用于写操作乐观并发控制。
CREATE TABLE IF NOT EXISTS equipment (
    equipment_id VARCHAR(64) NOT NULL PRIMARY KEY,
    maintenance_period_minutes BIGINT NOT NULL,
    version BIGINT NOT NULL,
    template_id VARCHAR(64),
    current_cycle_no BIGINT NOT NULL DEFAULT 1,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);
COMMENT ON TABLE equipment IS '设备主表：每台设备一行';
COMMENT ON COLUMN equipment.equipment_id IS '设备唯一标识（客户端提供）';
COMMENT ON COLUMN equipment.maintenance_period_minutes IS '保养周期（分钟），正整数，登记后不可修改';
COMMENT ON COLUMN equipment.version IS '设备版本号，初始 1；新增读数/修订/完成保养/证据提交/完工确认均校验 expectedVersion 并加一';
COMMENT ON COLUMN equipment.template_id IS '当前保养模板标识；NULL 表示未分配模板（沿用无证据包的旧保养流程）';
COMMENT ON COLUMN equipment.current_cycle_no IS '当前保养周期序号，初始 1；双人确认完工后加一进入下一周期';
COMMENT ON COLUMN equipment.created_at IS '登记时刻（UTC）';

-- 工时读数当前值表：reading_id 设备内唯一，同设备同一采样时刻仅一条。
CREATE TABLE IF NOT EXISTS reading (
    equipment_id VARCHAR(64) NOT NULL,
    reading_id VARCHAR(64) NOT NULL,
    sampled_at TIMESTAMP WITH TIME ZONE NOT NULL,
    cumulative_minutes BIGINT NOT NULL,
    revision_no INT NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    PRIMARY KEY (equipment_id, reading_id),
    CONSTRAINT uq_reading_sampled_at UNIQUE (equipment_id, sampled_at)
);
COMMENT ON TABLE reading IS '工时读数当前值：按采样时刻排序后累计分钟须单调不减';
COMMENT ON COLUMN reading.equipment_id IS '所属设备标识';
COMMENT ON COLUMN reading.reading_id IS '读数标识，设备内唯一';
COMMENT ON COLUMN reading.sampled_at IS 'UTC 采样时刻；同设备同一时刻仅允许一条读数';
COMMENT ON COLUMN reading.cumulative_minutes IS '当前累计工时（分钟），非负整数，随修订更新';
COMMENT ON COLUMN reading.revision_no IS '当前修订号，初始 1，每次修订加一';
COMMENT ON COLUMN reading.created_at IS '读数登记时刻（UTC）';
COMMENT ON COLUMN reading.updated_at IS '最近一次修订时刻（UTC）';

-- 读数修订历史：每次修订追加一行，保留全部历史值。
CREATE TABLE IF NOT EXISTS reading_revision (
    equipment_id VARCHAR(64) NOT NULL,
    reading_id VARCHAR(64) NOT NULL,
    revision_no INT NOT NULL,
    cumulative_minutes BIGINT NOT NULL,
    request_id VARCHAR(128) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    PRIMARY KEY (equipment_id, reading_id, revision_no)
);
COMMENT ON TABLE reading_revision IS '读数修订历史：revision_no=1 为初始登记值，其后每行对应一次修订';
COMMENT ON COLUMN reading_revision.equipment_id IS '所属设备标识';
COMMENT ON COLUMN reading_revision.reading_id IS '读数标识';
COMMENT ON COLUMN reading_revision.revision_no IS '修订号，从 1 开始递增';
COMMENT ON COLUMN reading_revision.cumulative_minutes IS '该修订版本的累计工时（分钟）';
COMMENT ON COLUMN reading_revision.request_id IS '产生该修订的请求 requestId';
COMMENT ON COLUMN reading_revision.created_at IS '该修订生效时刻（UTC）';

-- 保养记录：锚定某读数的特定修订号，保存锚点时刻与工时快照，不允许删除。
CREATE TABLE IF NOT EXISTS maintenance (
    maintenance_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    equipment_id VARCHAR(64) NOT NULL,
    reading_id VARCHAR(64) NOT NULL,
    anchor_revision_no INT NOT NULL,
    anchor_sampled_at TIMESTAMP WITH TIME ZONE NOT NULL,
    anchor_cumulative_minutes BIGINT NOT NULL,
    request_id VARCHAR(128) NOT NULL,
    completed_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_maintenance_equipment ON maintenance (equipment_id, anchor_sampled_at);
COMMENT ON TABLE maintenance IS '保养记录：锚点时间须严格晚于上次保养锚点；作为锚点的读数不可再修订';
COMMENT ON COLUMN maintenance.maintenance_id IS '保养记录自增主键';
COMMENT ON COLUMN maintenance.equipment_id IS '所属设备标识';
COMMENT ON COLUMN maintenance.reading_id IS '锚点读数标识';
COMMENT ON COLUMN maintenance.anchor_revision_no IS '锚点读数在保养完成时的修订号';
COMMENT ON COLUMN maintenance.anchor_sampled_at IS '锚点读数的 UTC 采样时刻（快照）';
COMMENT ON COLUMN maintenance.anchor_cumulative_minutes IS '锚点读数在保养完成时的累计工时快照（分钟）';
COMMENT ON COLUMN maintenance.request_id IS '完成保养请求的 requestId';
COMMENT ON COLUMN maintenance.completed_at IS '保养完成登记时刻（UTC）';

-- 保养模板版本头：每个模板一行，当前版本号用于模板修订串行化（行锁）。
CREATE TABLE IF NOT EXISTS maintenance_template_head (
    template_id VARCHAR(64) NOT NULL PRIMARY KEY,
    current_version INT NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);
COMMENT ON TABLE maintenance_template_head IS '保养模板版本头：current_version 为当前生效模板版本';
COMMENT ON COLUMN maintenance_template_head.template_id IS '保养模板标识';
COMMENT ON COLUMN maintenance_template_head.current_version IS '当前模板版本号，初始 1，每次修订加一';
COMMENT ON COLUMN maintenance_template_head.created_at IS '模板创建时刻（UTC）';

-- 保养模板检查项：按 (模板, 版本) 固化，模板修订生成新版本行集，不改写历史版本。
CREATE TABLE IF NOT EXISTS maintenance_template_item (
    template_id VARCHAR(64) NOT NULL,
    template_version INT NOT NULL,
    item_code VARCHAR(64) NOT NULL,
    item_name VARCHAR(128) NOT NULL,
    required_flag BOOLEAN NOT NULL,
    sort_order INT NOT NULL,
    PRIMARY KEY (template_id, template_version, item_code)
);
COMMENT ON TABLE maintenance_template_item IS '保养模板检查项：按模板版本固化，规范排序按 (sort_order, item_code) 升序';
COMMENT ON COLUMN maintenance_template_item.template_id IS '保养模板标识';
COMMENT ON COLUMN maintenance_template_item.template_version IS '模板版本号';
COMMENT ON COLUMN maintenance_template_item.item_code IS '检查项编码，模板版本内唯一';
COMMENT ON COLUMN maintenance_template_item.item_name IS '检查项名称';
COMMENT ON COLUMN maintenance_template_item.required_flag IS '是否必检项：必检项在证据包中必须恰有一个 PASS 结果';
COMMENT ON COLUMN maintenance_template_item.sort_order IS '模板内排序号，用于证据包规范排序';

-- 材料批次登记：批次全局唯一；撤销后不可再被证据包引用。
CREATE TABLE IF NOT EXISTS material_batch (
    batch_code VARCHAR(64) NOT NULL PRIMARY KEY,
    material_name VARCHAR(128) NOT NULL,
    status VARCHAR(16) NOT NULL,
    request_id VARCHAR(128) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    revoked_at TIMESTAMP WITH TIME ZONE,
    revoke_reason VARCHAR(256)
);
COMMENT ON TABLE material_batch IS '材料批次登记：status 为 ACTIVE 或 REVOKED；撤销为终态，不可恢复';
COMMENT ON COLUMN material_batch.batch_code IS '材料批次编码，格式 ^[A-Za-z0-9][A-Za-z0-9-]{2,63}$';
COMMENT ON COLUMN material_batch.material_name IS '材料名称';
COMMENT ON COLUMN material_batch.status IS '批次状态：ACTIVE 可用 / REVOKED 已撤销';
COMMENT ON COLUMN material_batch.request_id IS '登记请求的 requestId';
COMMENT ON COLUMN material_batch.created_at IS '登记时刻（UTC）';
COMMENT ON COLUMN material_batch.revoked_at IS '撤销时刻（UTC），未撤销为 NULL';
COMMENT ON COLUMN material_batch.revoke_reason IS '撤销原因，未撤销为 NULL';

-- 保养证据包：每次提交生成递增版本，版本行集不可变；固化周期、模板版本与提交人。
CREATE TABLE IF NOT EXISTS evidence_package (
    package_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    equipment_id VARCHAR(64) NOT NULL,
    cycle_no BIGINT NOT NULL,
    package_version INT NOT NULL,
    template_id VARCHAR(64) NOT NULL,
    template_version INT NOT NULL,
    submitted_by VARCHAR(64) NOT NULL,
    request_id VARCHAR(128) NOT NULL,
    submitted_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_evidence_package UNIQUE (equipment_id, cycle_no, package_version)
);
COMMENT ON TABLE evidence_package IS '保养证据包：设备周期内版本从 1 递增；每次提交整体替换并重校验完整最终包';
COMMENT ON COLUMN evidence_package.package_id IS '证据包自增主键';
COMMENT ON COLUMN evidence_package.equipment_id IS '所属设备标识';
COMMENT ON COLUMN evidence_package.cycle_no IS '保养周期序号（完工确认时的设备周期）';
COMMENT ON COLUMN evidence_package.package_version IS '证据包版本号，同一设备周期内从 1 递增';
COMMENT ON COLUMN evidence_package.template_id IS '提交时设备保养模板标识（快照）';
COMMENT ON COLUMN evidence_package.template_version IS '提交时模板版本号（快照），后续模板修订不改写';
COMMENT ON COLUMN evidence_package.submitted_by IS '提交人（维护人员）；提交人不能确认本人提交的完工';
COMMENT ON COLUMN evidence_package.request_id IS '提交请求的 requestId';
COMMENT ON COLUMN evidence_package.submitted_at IS '提交时刻（UTC）';

-- 证据包检查项结果：随证据包版本固化，不可变；每项在包内至多一条。
CREATE TABLE IF NOT EXISTS evidence_item_result (
    package_id BIGINT NOT NULL,
    item_code VARCHAR(64) NOT NULL,
    item_name VARCHAR(128) NOT NULL,
    required_flag BOOLEAN NOT NULL,
    sort_order INT NOT NULL,
    result VARCHAR(8) NOT NULL,
    note VARCHAR(256),
    PRIMARY KEY (package_id, item_code)
);
COMMENT ON TABLE evidence_item_result IS '证据包检查项结果：result 为 PASS 或 FAIL；名称/必检/排序为提交时模板快照';
COMMENT ON COLUMN evidence_item_result.package_id IS '所属证据包标识';
COMMENT ON COLUMN evidence_item_result.item_code IS '检查项编码（提交时必须属于设备当前模板版本）';
COMMENT ON COLUMN evidence_item_result.item_name IS '检查项名称（提交时模板快照）';
COMMENT ON COLUMN evidence_item_result.required_flag IS '是否必检项（提交时模板快照）';
COMMENT ON COLUMN evidence_item_result.sort_order IS '规范排序号（提交时模板快照）';
COMMENT ON COLUMN evidence_item_result.result IS '检查结果：PASS 或 FAIL；存在 FAIL 时不可完工';
COMMENT ON COLUMN evidence_item_result.note IS '检查备注，可空';

-- 证据包材料批次摘要：同一设备周期内批次不可重复（跨版本唯一约束兜底）。
CREATE TABLE IF NOT EXISTS evidence_material (
    package_id BIGINT NOT NULL,
    equipment_id VARCHAR(64) NOT NULL,
    cycle_no BIGINT NOT NULL,
    batch_code VARCHAR(64) NOT NULL,
    material_name VARCHAR(128) NOT NULL,
    quantity BIGINT,
    unit VARCHAR(16),
    summary VARCHAR(256) NOT NULL,
    PRIMARY KEY (package_id, batch_code),
    CONSTRAINT uq_evidence_material_cycle UNIQUE (equipment_id, cycle_no, batch_code)
);
COMMENT ON TABLE evidence_material IS '证据包材料批次摘要：每个证据包至少一条；同一设备周期内批次不可重复';
COMMENT ON COLUMN evidence_material.package_id IS '所属证据包标识';
COMMENT ON COLUMN evidence_material.equipment_id IS '所属设备标识（周期唯一约束冗余列）';
COMMENT ON COLUMN evidence_material.cycle_no IS '保养周期序号（周期唯一约束冗余列）';
COMMENT ON COLUMN evidence_material.batch_code IS '材料批次编码，须已登记且未撤销';
COMMENT ON COLUMN evidence_material.material_name IS '材料名称（提交时批次快照）';
COMMENT ON COLUMN evidence_material.quantity IS '使用数量，正整数，可空（未知）';
COMMENT ON COLUMN evidence_material.unit IS '数量单位（如 pcs/L），可空';
COMMENT ON COLUMN evidence_material.summary IS '材料批次摘要说明';

-- 双人完工确认：另一维护角色确认当前证据包版本后原子完成保养；记录不可变。
CREATE TABLE IF NOT EXISTS completion_confirmation (
    confirmation_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    equipment_id VARCHAR(64) NOT NULL,
    cycle_no BIGINT NOT NULL,
    package_version INT NOT NULL,
    template_version INT NOT NULL,
    confirmed_by VARCHAR(64) NOT NULL,
    request_id VARCHAR(128) NOT NULL,
    maintenance_id BIGINT NOT NULL,
    confirmed_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_confirmation_cycle UNIQUE (equipment_id, cycle_no)
);
COMMENT ON TABLE completion_confirmation IS '双人完工确认：确认人不得为证据包提交人；确认即原子完成保养并重置下一周期';
COMMENT ON COLUMN completion_confirmation.confirmation_id IS '完工确认自增主键';
COMMENT ON COLUMN completion_confirmation.equipment_id IS '所属设备标识';
COMMENT ON COLUMN completion_confirmation.cycle_no IS '完成的保养周期序号；每周期至多一条确认';
COMMENT ON COLUMN completion_confirmation.package_version IS '被确认的证据包版本号';
COMMENT ON COLUMN completion_confirmation.template_version IS '确认时的模板版本号（快照）';
COMMENT ON COLUMN completion_confirmation.confirmed_by IS '确认人（另一维护角色，不得为提交人）';
COMMENT ON COLUMN completion_confirmation.request_id IS '确认请求的 requestId';
COMMENT ON COLUMN completion_confirmation.maintenance_id IS '原子生成的保养记录标识';
COMMENT ON COLUMN completion_confirmation.confirmed_at IS '确认时刻（UTC）';

-- 完工更正附录：完工后发现错误只能追加附录，不重开周期、不改写历史。
CREATE TABLE IF NOT EXISTS maintenance_appendix (
    appendix_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    maintenance_id BIGINT NOT NULL,
    equipment_id VARCHAR(64) NOT NULL,
    created_by VARCHAR(64) NOT NULL,
    content VARCHAR(512) NOT NULL,
    request_id VARCHAR(128) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_appendix_maintenance ON maintenance_appendix (maintenance_id, appendix_id);
COMMENT ON TABLE maintenance_appendix IS '保养更正附录：追加式、不可变；不修改原保养记录、读数与工时历史';
COMMENT ON COLUMN maintenance_appendix.appendix_id IS '附录自增主键';
COMMENT ON COLUMN maintenance_appendix.maintenance_id IS '所属保养记录标识';
COMMENT ON COLUMN maintenance_appendix.equipment_id IS '所属设备标识';
COMMENT ON COLUMN maintenance_appendix.created_by IS '附录创建人';
COMMENT ON COLUMN maintenance_appendix.content IS '更正内容说明';
COMMENT ON COLUMN maintenance_appendix.request_id IS '创建请求的 requestId';
COMMENT ON COLUMN maintenance_appendix.created_at IS '创建时刻（UTC）';

-- 幂等去重表：requestId 全局唯一；仅成功结果占键，失败回滚不占键。
CREATE TABLE IF NOT EXISTS idempotency_request (
    request_id VARCHAR(128) NOT NULL PRIMARY KEY,
    operation VARCHAR(48) NOT NULL,
    request_fingerprint VARCHAR(512) NOT NULL,
    response_body CLOB NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);
COMMENT ON TABLE idempotency_request IS '写操作幂等去重：同键同参重放原成功结果，同键异参返回 409';
COMMENT ON COLUMN idempotency_request.request_id IS '全局唯一请求标识';
COMMENT ON COLUMN idempotency_request.operation IS '操作类型（登记设备/读数/修订/保养/模板/材料/证据/确认/附录）';
COMMENT ON COLUMN idempotency_request.request_fingerprint IS '业务参数指纹（不含 requestId），用于同键异参判定';
COMMENT ON COLUMN idempotency_request.response_body IS '原成功响应报文（JSON），重放时原样返回';
COMMENT ON COLUMN idempotency_request.created_at IS '首次成功处理时刻（UTC）';
